def main() -> int:
    if not os.path.isdir(DEFAULT_APP_DIR):
        print(f"reference app dir missing: {DEFAULT_APP_DIR}", file=sys.stderr)
        return 2
    rev = subprocess.run(
        ["git", "-C", os.path.dirname(DEFAULT_APP_DIR), "rev-parse", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()
    if rev != PINNED_REV:
        print(f"reference rev {rev} != pinned {PINNED_REV}", file=sys.stderr)
        return 2
    env = dict(os.environ)
    env["GC_APP_DIR"] = DEFAULT_APP_DIR
