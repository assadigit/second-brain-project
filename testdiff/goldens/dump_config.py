def main() -> int:
    out_c = REPO_ROOT / "internal" / "config" / "testdata"
    out_c.mkdir(parents=True, exist_ok=True)
    scratch = Path(tempfile.mkdtemp(prefix="curator-cfgmem-"))

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "user_config.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_CONFIG"] = str(out_c)
    env["CONFIG_MEMORY_PATH"] = str(scratch / ".gitcurator")
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    shutil.rmtree(scratch, ignore_errors=True)
    print(f"[goldens] generated internal/config/testdata "
          f"({summary['fill_cases']} fill + {summary['mirror_cases']} mirror cases)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] example dump: {summary['example_bytes']} bytes / "
          f"{summary['example_keys']} keys; round-trip filled "
          f"{summary['round_trip_filled']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
