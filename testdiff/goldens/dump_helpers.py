#!/usr/bin/env python3
"""Golden generator for T-17 (internal/helpers — the Python-semantics
helper library, doc 05 §3 items 2/3/4/6/7/12/13/16 + the session's
promoted string helpers).

THE LAW: goldens are GENERATED by running the unmodified Python reference
interpreter's own semantics (the helpers port Python BUILTINS, not
GitCurator code — str[:n], str.rstrip(chars), round(x, n),
dict.fromkeys, os.path.normcase, f"{n:,}", str.lower, str()) via
the reference venv; never hand-typed.

What it pins (helpers_corpus.golden.json):
  cut_runes       code-point slicing s[:n] (U+0130, U+2026, 🗑️+VS16 —
                  two code points — CJK, n=0, n>len)
  strip_chars     str.strip/lstrip/rstrip(chars) CHAR-SET semantics
                  (trailing slashes, punctuation, empty set, 🗑️ bytes,
                  U+0130 in the set)
  round_half_even Python round(x, n) — banker's rounding on the EXACT
                  binary value (2.675→2.67, 0.125→0.12, 2.5→2, 3.5→4,
                  -0.5→-0.0 …)
  ordered_dedupe  dict.fromkeys order (first occurrence wins; U+0130 ≠ i)
  normcase        os.path.normcase — BOTH columns: posixpath (identity)
                  and ntpath (slash-fold + FULL Unicode lower: İ → i̇)
  format_comma    f"{n:,}" (incl. negatives, int64 extremes)
  py_lower        str.lower (İ full mapping, final sigma) — the corpus
                  promoted from links
  py_str          str(v) for the parity value shapes (5 vs 5.0, 1e15
                  positional, True/False, None → "None")
  py_repr         repr() slim corpus (the full battery stays pinned in
                  internal/prompts' golden)
  splitlines      str.splitlines boundaries (slim; the full battery
                  stays pinned in internal/taxonomy's golden)
  stripws         str.strip()/lstrip()/rstrip() Unicode whitespace
                  (slim; full battery in taxonomy's golden)

Usage (from the repo root):
    python3 testdiff/goldens/dump_helpers.py

Env overrides: GC_PYTHON (same conventions as ../harness.py).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")

PAYLOAD = r'''
import json, ntpath, os, posixpath, sys

OUT_H = os.environ["GOLDEN_OUT_DIR_HELPERS"]

def canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n"

def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)

# ---------------------------------------------------------------------------
# 1. Code-point slicing (s[:n]) — doc 05 §3 item 3.
# ---------------------------------------------------------------------------
CUT_CASES = [
    ["hello", 3], ["hello", 0], ["hello", 99], ["", 5],
    ["数据科学库", 2], ["数据科学库", 4],
    ["🗑️ delete", 1], ["🗑️ delete", 2], ["🗑️", 1],
    ["İstanbul", 1], ["İstanbul", 3],
    ["…ellipsis", 1], ["…", 1],
    ["a\u0307b", 2], ["mixed 数据 🗑️ text", 8],
    ["x" * 40, 35], ["\U0001F600\U0001F601", 1],
]
cut_doc = [[s, n, s[:n]] for s, n in CUT_CASES]

# ---------------------------------------------------------------------------
# 2. Character-set strip (doc 05 §3 items 6/7).
# ---------------------------------------------------------------------------
STRIP_CASES = [
    ["https://x.com///", "/"],
    ["hello!!!", "!"],
    ["**bold**", "*"],
    ["  padded  ", ""],          # empty set strips NOTHING
    ["-_-", "-"],
    ["abc", "xyz"],
    [".hidden.", "."],
    ["trash 🗑️🗑️", "🗑️"],
    ["İstanbulİ", "İ"],
    ["…text…", "…"],
    ["/vault/path/", "/"],
    ["ends-with-space ", " "],
    ["a b c", "ac"],
    ["\t \n mixed \t", " \t\n"],
    ["", "abc"], ["", ""],
]
strip_doc = [[s, chars, s.rstrip(chars), s.strip(chars), s.lstrip(chars)]
             for s, chars in STRIP_CASES]

# ---------------------------------------------------------------------------
# 3. round(x, n) — banker's rounding (doc 05 §3 item 4).
# ---------------------------------------------------------------------------
ROUND_CASES = [
    [2.5, 0], [3.5, 0], [0.5, 0], [1.5, 0], [-0.5, 0], [-1.5, 0],
    [4.5, 0], [5.5, 0],
    [2.675, 2], [2.665, 2], [0.125, 2], [0.135, 2], [1.005, 2],
    [2.235, 2], [-2.675, 2], [-0.125, 2], [0.145, 2], [2.685, 2],
    [1.2345, 2], [8.275, 2], [8.285, 2],
    [2.05, 1], [2.15, 1], [2.25, 1], [2.35, 1],
    [0.0, 2], [1.0, 2], [123.456, 2], [123.456, 1], [123.456, 0],
    [-123.456, 2], [100.0, 2], [0.044999999999999998, 2],
    [1e15, 2], [1e-7, 8], [1234567.891, 2],
]
round_doc = [[x, n, round(x, n)] for x, n in ROUND_CASES]

# ---------------------------------------------------------------------------
# 4. dict.fromkeys ordered dedupe (doc 05 §3 item 16).
# ---------------------------------------------------------------------------
DEDUPE_CASES = [
    ["a", "b", "a", "c", "b"],
    ["İ", "i", "İ"],
    ["Tag", "tag", "TAG", "b"],
    [1, 2, 1, 3, 2, 1],
    [],
    ["x"],
    ["🗑️", "🗑️", "…", "🗑️"],
    [0, 0, 1, 0],
]
dedupe_doc = [[case, list(dict.fromkeys(case))] for case in DEDUPE_CASES]

# ---------------------------------------------------------------------------
# 5. os.path.normcase (doc 05 §3 item 13) — both platforms' columns.
# ---------------------------------------------------------------------------
NORMCASE_CASES = [
    "C:\\Foo/Bar", "ABC.MD", "İ", "Σ", "ΣΟΦΟΣ", "a/b\\c",
    "already/lower.md", "", "Plain.txt", "MIXED/Path\\FILE",
    "x/i̇", " Ou T ",
]
normcase_doc = [[s, posixpath.normcase(s), ntpath.normcase(s)]
                for s in NORMCASE_CASES]

# ---------------------------------------------------------------------------
# 6. f"{n:,}" — the promoted formatComma.
# ---------------------------------------------------------------------------
COMMA_CASES = [0, 1, 9, 10, 99, 100, 999, 1000, 9999, 10000, 123456,
               1234567, 9876543210, 999999999999, -1, -999, -1234567,
               9223372036854775807, -9223372036854775808]
comma_doc = [[n, f"{n:,}"] for n in COMMA_CASES]

# ---------------------------------------------------------------------------
# 7. str.lower (the links corpus, promoted to the helpers home).
# ---------------------------------------------------------------------------
LOWER_CASES = [
    "HELLO", "hello", "İstanbul", "ASIMPLEΣ", "Σ", "Σ ΣΣ",
    "ADSATZ", "OIΣ", "MiXeD 123 ABC", "", "ς", "Ϗ",
    "ABC.ABC.COM", "Xn--Pyp", "ÖÇÜ İĞ", "ss",
]
lower_doc = [[s, s.lower()] for s in LOWER_CASES]

# ---------------------------------------------------------------------------
# 8. str(v) for the parity shapes.
# ---------------------------------------------------------------------------
STR_CASES = [5, 5.0, 2.5, 1e15, 1e-05, 1e16, 0.1, 3.141592653589793,
             True, False, "text", None, "0", 0, -1.5, 1234.5]
str_doc = [[v, str(v)] for v in STR_CASES]

# ---------------------------------------------------------------------------
# 9. repr() slim corpus.
# ---------------------------------------------------------------------------
REPR_CASES = ["simple", "it's", 'say "hi"', "tab\there", "nl\nhere",
              "你好", "é", "nbsp\xa0", "", "a\\b"]
repr_doc = [[s, repr(s)] for s in REPR_CASES]

# ---------------------------------------------------------------------------
# 10. splitlines + strip whitespace (slim batteries).
# ---------------------------------------------------------------------------
SPLITLINES = ["a\nb", "a\r\nb", "a\rb", "a\u2028b", "a\x1cb", "", "x\n",
              "a\n\nb", "plain"]
splitlines_doc = [[s, s.splitlines()] for s in SPLITLINES]
STRIPWS = ["  hello  ", "\xa0nbsp\xa0", "\x1cctrl\x1c", " \u000bmixed\u000c ",
           "\t tab \t", "**stars**", "\u2028ls\u2028"]
stripws_doc = [[s, [s.strip(), s.lstrip(), s.rstrip()]] for s in STRIPWS]

doc = {
    "schema": 1,
    "cut_runes": cut_doc,
    "strip_chars": strip_doc,
    "round_half_even": round_doc,
    "ordered_dedupe": dedupe_doc,
    "normcase": normcase_doc,
    "format_comma": comma_doc,
    "py_lower": lower_doc,
    "py_str": str_doc,
    "py_repr": repr_doc,
    "splitlines": splitlines_doc,
    "stripws": stripws_doc,
}
write_text(os.path.join(OUT_H, "helpers_corpus.golden.json"), canon(doc))
print(json.dumps({
    "cut": len(cut_doc), "strip": len(strip_doc), "round": len(round_doc),
    "dedupe": len(dedupe_doc), "normcase": len(normcase_doc),
    "comma": len(comma_doc), "lower": len(lower_doc), "str": len(str_doc),
}))
'''


def main() -> int:
    out_h = REPO_ROOT / "internal" / "helpers" / "testdata"
    out_h.mkdir(parents=True, exist_ok=True)

    # The helpers port PYTHON BUILTINS — the pinned interpreter itself is
    # the reference; the GitCurator rev check still guards the rig.
    app_dir = Path(os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app"))
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GOLDEN_OUT_DIR_HELPERS"] = str(out_h)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/helpers/testdata "
          f"({summary['cut']} cut + {summary['strip']} strip + "
          f"{summary['round']} round + {summary['dedupe']} dedupe + "
          f"{summary['normcase']} normcase + {summary['comma']} comma + "
          f"{summary['lower']} lower + {summary['str']} str cases)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
