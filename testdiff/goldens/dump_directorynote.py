def sweep_flow(name, vault_fn, blocked, dry=False):
    vault = os.path.join(TMP, "sweep-" + name)
    os.makedirs(vault, exist_ok=True)
    LOGS.clear()
    vault_fn(vault)
    if dry:
        dryrun.enable()
        dryrun.clear()
    report = wd.sweep_banned_notes(vault, blocked, log=log)
    if dry:
        dryrun.disable()
        dryrun.clear()
    out = {
        "report": report,
        "logs": list(LOGS),
        "quarantine": listing(os.path.join(vault, ".trash", "banned-domains")),
    }
    return vault, out


