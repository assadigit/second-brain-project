"""Golden generator for T-43 (internal/handdelivery — core/
hand_delivery.py:88-907, the module T-40 floored and T-43 completes:
the Chrome launch family, walled_retry_rows, consume_delivered,
pending_hand_links, stamp_hand_rows, hand_fetch_result).

THE LAW: goldens are GENERATED by running the unmodified Python
reference app (assadigit/GitCurator @ 98f4fc7) — never hand-typed,
never edited by hand. This generator exercises the reference's own
hand_delivery module directly (it is core/, stdlib-only — no
GUI-layer stubs needed, unlike dump_githubpipeline.py) and dumps the
results into the Go package's testdata/ directory, where the Go
characterization tests byte-compare their port.

The T-40 sections (enqueue / README / queue.json / suggested_filename
/ take_hand_delivered + redo + heal) are already byte-pinned by
dump_websitepipeline.py's golden — extend, never duplicate. THIS
golden pins the T-43 surface only.

NO PER-RUN FACTS INSIDE: hand_delivery's `time` is stubbed to a fixed
strftime (2026-10-17) so every stamp (queued / consumed / the table
dates) is a static fact; the state DB rows for walled_retry_rows are
timeless (url / last_error / attempts only); every flow rides its own
tempdir subtree, folded to <TMP> in the dump.

The auto-door page in consume_delivered is a REAL page (the fifth
door's own verdict passes it in the reference; the port's honest
degrade — PageIsRealFn unset until T-44 — agrees). The ERROR-page
auto-door legs (the discard battery) are T-44's, landed when
internal/chrometabs wires the seam.

What it pins (spec-core-hand-delivery.md — T-43's contract):

  internal/handdelivery/testdata/
    handdelivery.golden.json    the corpus:
        walled_retry_rows     the picker's data — the real
                              WebsiteStateDB's rows (input) and the
                              walled filter's output (url / wall /
                              attempts)
        consume_delivered     the batch consume flow (five links:
                              owner-save taken, empty page keeps
                              waiting, pre-consumed skipped, the
                              auto-door real page taken, no-file
                              skipped; an orphan file ignored) — the
                              taken rows + the queue.json bytes after
                              + the log lines
        stamp_hand_rows       the master-table 🖐 queue stamp — the
                              stamped count + the table bytes (the
                              Last-updated refresh included)
        pending_hand_links    the fifth door's to-do list after the
                              consume (the no-file rows; the empty
                              page's file counts as landed)
        hand_fetch_result     the FetchResult shape for both wordings
                              (the fourth door's and the fifth's
                              auto story)

Usage (from the repo root):
    python3 testdiff/goldens/dump_handdelivery.py

Env overrides: GC_PYTHON / GC_APP_DIR (same conventions as ../harness.py).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")
DEFAULT_APP_DIR = os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app")

OUT_DIR = REPO_ROOT / "internal" / "handdelivery" / "testdata"
OUT_FILE = OUT_DIR / "handdelivery.golden.json"

PAYLOAD = r'''
import json
import os
import sys
import tempfile

sys.path.insert(0, os.environ["GC_APP_DIR"])
from gitcurator.core import dryrun
from gitcurator.core import hand_delivery as hd
from gitcurator.core.website_state import WebsiteStateDB

dryrun.disable()
dryrun.clear()


# ---- the frozen clock (no per-run facts inside the golden) ----------
class _FixedTime:
    @staticmethod
    def strftime(fmt):
        if fmt == "%Y-%m-%d %H:%M":
            return "2026-10-17 12:00"
        if fmt == "%Y-%m-%d":
            return "2026-10-17"
        raise AssertionError("unexpected strftime format " + fmt)


hd.time = _FixedTime

OUT = {}
TMP = tempfile.mkdtemp(prefix="handgold-")


def fold(s):
    return s.replace(TMP, "<TMP>")


def read_file(path):
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        return f.read()


LOGS = []


def _log(msg, level="info"):
    LOGS.append("[%s] %s" % (level, msg))


# --- 1. walled_retry_rows (the picker's data; a real state DB) --------
db = WebsiteStateDB(db_path=os.path.join(TMP, "walled.db"))
try:
    WALL = ("HTTP 403 — bot defense (server: cloudflare; "
            "challenge) | chrome-impersonated: HTTP 403")
    db.enqueue_retry("https://walled.example.net/article", WALL)
    db.enqueue_retry("https://walled.example.net/article", WALL)
    db.enqueue_retry("https://dead.example.org/x", "HTTP 404 — gone")
    db.enqueue_retry("https://ok.example.org/y", "timeout")
    rows = db.all_retry_rows() or []
    OUT["walled_retry_rows"] = {
        "input": [{"url": r.get("url"), "last_error": r.get("last_error"),
                   "attempts": r.get("attempts")} for r in rows],
        "output": [dict(r) for r in hd.walled_retry_rows(db)],
    }
finally:
    db.close()

# --- 2. consume_delivered (the batch consume flow) --------------------
VAULT = os.path.join(TMP, "vault", "websites")
A = "https://alpha.example/walled"
B = "https://beta.example/empty"
C = "https://gamma.example/consumed"
D = "https://delta.example/auto"
E = "https://epsilon.example/waiting"
F = "https://zeta.example/waiting-too"
WALLS = {A: "HTTP 403 — bot defense (server: cloudflare)",
         B: "HTTP 403 — refused", C: "ssl handshake failed",
         E: "HTTP 429 — rate limited"}
LOGS.clear()
hd.enqueue_hand_delivery(VAULT, [A, B, C, E], walls=WALLS, log=_log)
hd.enqueue_hand_delivery(VAULT, [D, F],
                         walls={D: "fingerprint mismatch",
                                F: "HTTP 405"},
                         log=_log, door="auto")
# a pre-consumed row (the record's own stamp — an earlier batch took it)
hdq = hd._read_queue(VAULT)
hdq["links"][C]["consumed"] = "2026-10-01 10:00"
with open(hd.queue_path(VAULT), "w", encoding="utf-8", newline="") as f:
    f.write(json.dumps(hdq, indent=2, ensure_ascii=False))

HD_DIR = hd.hand_delivery_dir(VAULT)
os.makedirs(HD_DIR, exist_ok=True)


def deliver(url, body):
    path = os.path.join(HD_DIR, hd.suggested_filename(url))
    with open(path, "wb") as f:
        f.write(body)
    return path


deliver(A, b"<html><head><title>The Walled Page</title></head>"
           b"<body>the content the browser sees</body></html>")
deliver(B, b"   ")            # the empty page — keeps waiting
deliver(D, b"<html><head><title>Auto Real</title></head><body>"
            b"real live DOM content long enough to be a real page "
            b"for the fifth door's own verdict</body></html>")
with open(os.path.join(HD_DIR, "random-orphan.html"), "wb") as f:
    f.write(b"<html></html>")   # an orphan — ignored

LOGS.clear()
taken = hd.consume_delivered(VAULT, log=_log)
OUT["consume_delivered"] = {
    "taken": [{"url": it["url"], "wall": it["wall"],
               "file": fold(it["file"]),
               "body": it["body"].decode("utf-8", errors="replace")}
              for it in taken],
    "queue_after": fold(read_file(hd.queue_path(VAULT))),
    "logs": [fold(m) for m in LOGS],
}

# --- 4. pending_hand_links (the fifth door's to-do list) --------------
OUT["pending_hand_links"] = [dict(l) for l in hd.pending_hand_links(VAULT)]

# --- 3. stamp_hand_rows (the master-table queue stamp) ----------------
TV = os.path.join(TMP, "stamptable")
os.makedirs(os.path.join(TV, "_review"), exist_ok=True)
TABLE = os.path.join(TV, "_review", "DECOMMISSIONED.md")
table_lines = [
    "# Review Master Table — decommission or approve",
    "",
    "> Last updated: 2001-01-01 00:00",
    "",
    "| # | Date | URL | Domain | Source | Status | Notes |",
    "|---|------|-----|--------|--------|--------|-------|",
    "| - | 2026-10-01 | https://hand1.example/a | hand1.example "
    "| retry backlog | unreviewed | first |",
    "| 🖐 | 2026-10-01 | https://hand2.example/b | hand2.example "
    "| owner | hand | second |",
    "| - | 2026-10-01 | https://other.example/c | other.example "
    "| retry backlog | unreviewed | third |",
]
with open(TABLE, "w", encoding="utf-8", newline="") as f:
    f.write("\n".join(table_lines) + "\n")
stamped = hd.stamp_hand_rows(TV, ["https://hand1.example/a",
                                  "https://hand2.example/b"],
                             log=_log)
OUT["stamp_hand_rows"] = {
    "stamped": stamped,
    "table": fold(read_file(TABLE)),
}

# --- 5. hand_fetch_result (both wordings) -----------------------------
BODY = b"<html><head><title>Story</title></head><body>x</body></html>"
r4 = hd.hand_fetch_result(A, BODY, "HTTP 403 — bot defense", None)
r5 = hd.hand_fetch_result(D, BODY, "fingerprint mismatch", "auto")
def fres(r):
    return {"url": r.url, "final_url": r.final_url, "status": r.status,
            "http_status": r.http_status, "content_type": r.content_type,
            "charset": r.charset, "reason": r.reason, "ok": r.ok,
            "text": r.text}
OUT["hand_fetch_result"] = {"fourth_door": fres(r4),
                            "fifth_door_auto": fres(r5)}

print(json.dumps(OUT, sort_keys=True, ensure_ascii=False, indent=2))
'''


def main() -> int:
    if not os.path.isdir(DEFAULT_APP_DIR):
        print(f"reference app dir missing: {DEFAULT_APP_DIR}", file=sys.stderr)
        return 2
    rev = subprocess.run(
        ["git", "-C", os.path.dirname(DEFAULT_APP_DIR), "rev-parse", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()
    if rev != PINNED_REV:
        print(f"reference rev {rev} != pinned {PINNED_REV}", file=sys.stderr)
        return 2
    env = dict(os.environ)
    env["GC_APP_DIR"] = DEFAULT_APP_DIR
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run(
        [DEFAULT_PY, "-c", PAYLOAD], capture_output=True, text=True, env=env,
    )
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(proc.stdout, encoding="utf-8")
    print(f"wrote {OUT_FILE} ({len(proc.stdout)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
