class _TempfileRecorder:
    def __init__(self, real):
        self._real = real
        self.dirs = []

    def mkdtemp(self, *a, **k):
        d = self._real.mkdtemp(*a, **k)
        self.dirs.append(d)
        return d

    def __getattr__(self, name):
        return getattr(self._real, name)


class _ShutilRecorder:
    def __init__(self, real):
        self._real = real
        self.removed = []

    def rmtree(self, path, ignore_errors=False, **k):
        self.removed.append(path)          # recorded, NEVER deleted

    def __getattr__(self, name):
        return getattr(self._real, name)


_LLM = []
