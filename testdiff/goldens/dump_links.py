def main() -> int:
    out_dir = REPO_ROOT / "internal" / "links" / "testdata"
    out_dir.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "links.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}", file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR"] = str(out_dir)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    print(f"[goldens] generated {out_dir}/link_grammar.golden.json + import_corpus.txt")
    print(f"[goldens] reference rev: {rev}")
    print(f"[goldens] {proc.stdout.strip()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
