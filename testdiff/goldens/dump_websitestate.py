def main() -> int:
    out = REPO_ROOT / "internal" / "websitepipeline" / "testdata"
    out.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "website_state.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_WEBSITESTATE"] = str(out)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/websitepipeline testdata "
          f"({len(summary)} stat keys)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] key cases: {summary['key_cases']} "
          f"(backoff rows: {summary['backoff_rows']})")
    print(f"[goldens] fixture sha256: {summary['fixture_sha256']} "
          f"(clean close, no sidecars: {summary['no_sidecars']})")
    print(f"[goldens] pragmas through the reference's own open: "
          f"{summary['pragmas']}")
    print(f"[goldens] table rows: {summary['table_rows']}")
    print(f"[goldens] schema objects: {summary['schema_objects']}")
    print(f"[goldens] behavior probes: {summary['behavior_probes']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
