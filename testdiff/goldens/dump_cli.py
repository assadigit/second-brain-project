def main() -> int:
    if not os.path.isdir(DEFAULT_APP_DIR):
        print(f"reference app dir missing: {DEFAULT_APP_DIR}", file=sys.stderr)
        return 2
    rev = subprocess.run(
        ["git", "-C", os.path.dirname(DEFAULT_APP_DIR), "rev-parse", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()
    if rev != PINNED_REV:
        print(f"reference rev {rev} != pinned {PINNED_REV}", file=sys.stderr)
        return 2
    env = dict(os.environ)
    env["GC_APP_DIR"] = DEFAULT_APP_DIR
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["NO_COLOR"] = "1"
    env.pop("COLUMNS", None)
    # The determinism proof is part of every regeneration: run the
    # payload twice; the dump must be byte-identical or nothing is
    # written.
    dumps = []
    for _ in range(2):
        proc = subprocess.run(
            [DEFAULT_PY, "-c", PAYLOAD], capture_output=True, text=True,
            env=env,
        )
        if proc.returncode != 0:
            print(proc.stderr, file=sys.stderr)
            return 1
        dumps.append(proc.stdout)
    if dumps[0] != dumps[1]:
        print("the two runs differ — golden NOT written (determinism "
              "proof failed)", file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(dumps[0], encoding="utf-8")
    print(f"wrote {OUT_FILE} ({len(dumps[0])} bytes, two-run "
          f"byte-identical)")
    return 0


