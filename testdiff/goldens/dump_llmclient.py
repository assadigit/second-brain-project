# ---------------------------------------------------------------------------
# Per-run-fact normalization: a result is scrubbed through THIS
# scenario's server URLs before dumping — <API> before <ROOT> (the API
# string contains the ROOT), <DEADURL> for dead ports. The Go tests
# apply the same replacement with their own server URLs, so the golden
# carries only deterministic bytes.
# ---------------------------------------------------------------------------


def root_of(srv):
    return 'http://127.0.0.1:%d' % srv.server_port


def norm(obj, root=None, dead=None):
    api = (root + '/v1') if root else None

    def rep(x):
        if api:
            x = x.replace(api, '<API>')
        if root:
            x = x.replace(root, '<ROOT>')
        if dead:
            x = x.replace(dead, '<DEADURL>')
        return x

    def walk(o):
        if isinstance(o, dict):
            return {k: walk(v) for k, v in o.items()}
        if isinstance(o, (list, tuple)):
            return [walk(v) for v in o]
        if isinstance(o, str):
            return rep(o)
        return o

    return walk(obj)


