#!/usr/bin/env python3
"""Golden generator for T-21 (internal/notestate — core/note_state.py).

THE LAW: goldens are GENERATED by running the unmodified Python reference
app (assadigit/GitCurator @ 98f4fc7) — never hand-typed, never edited by
hand. This generator exercises the reference's own note-state law
(core/note_state.py NoteStateDB: own connection + RLock on the SAME
cache.db path family, busy_timeout=30000, the three tables) and the pure
detectors (compute_fingerprint's recall-block strip + the folder ->
category reverse map), and dumps them into the Go package's testdata/
directory, where the Go characterization tests byte-compare their own
port.

What it pins (spec-core-note-state.md — T-21's contract):

  internal/notestate/testdata/
    notestate_pure.golden.json       the pure-logic corpus:
                                      (a) compute_fingerprint over fixed
                                      inputs — plain, unicode, recall
                                      blocks (one + two, the non-greedy
                                      DOTALL strip), whitespace tails,
                                      empty, AND the invalid-UTF-8 battery
                                      (byte-array inputs decoded exactly
                                      like the reference's own file reads:
                                      utf-8 errors='replace' then the
                                      strip+sha256 — pinning the
                                      replacement semantics byte-exact),
                                      with the STRIPPED intermediate
                                      included so the strip law itself is
                                      pinned, not just the hash;
                                      (b) the folder_category matrix: all
                                      24 CATEGORY_FOLDERS reverse hits
                                      plus root/_review/nested/unmapped/
                                      backslash/edge inputs.
    notestate_python_created.db       THE PYTHON-CREATED FIXTURE (the T-21
                                      acceptance input): built via the
                                      reference's own NoteStateDB methods —
                                      upsert (incl. the update-in-place
                                      same vault+source probe and the NULL
                                      category _review row), record_note
                                      (content given; the websites
                                      normalizer probe via
                                      links.normalize_website_url AND the
                                      GitHub default normalize_url
                                      trailing-slash keying), set_locked,
                                      log_correction (paths+note and the
                                      defaulted second call), dismiss +
                                      the re-dismiss INSERT OR REPLACE
                                      probe + clear_dismissed round-trip
                                      probes. Clean close then copied
                                      verbatim. Regeneration rewrites it
                                      TOGETHER with its content golden
                                      (an ATOMIC PAIR — the timestamps
                                      inside are the reference's own now()
                                      strings and necessarily change per
                                      run; the pair's internal consistency
                                      is what the golden proves, via
                                      fixture_sha256).
    notestate_fixture_content.golden.json
                                      the fixture's exact contents: every
                                      table's raw columns (read-only
                                      introspection of reference-written
                                      rows — the writes go ONLY through
                                      the reference's methods), the pragma
                                      facts the reference's own open sets
                                      (busy_timeout only — NoteStateDB
                                      deliberately does NOT set WAL; the
                                      Go side's unified WAL law is the
                                      documented store-package divergence),
                                      the no-sidecars-after-close fact,
                                      the fixture sha256 (the atomic-pair
                                      tie), and a getter battery read back
                                      through the reference's own getters.
    notestate_schema.golden.json      the DDL the reference's __init__
                                      produces (sqlite_master type/name/
                                      sql, ordered) + PRAGMA table_info
                                      columns — the byte-exact schema the
                                      Go side must adopt as-is (ADR-0003:
                                      no migrations, adopt the existing
                                      database). NOTE: every column is
                                      TEXT/INTEGER-declared — no
                                      DATE/DATETIME/TIMESTAMP column
                                      exists in these tables, so the
                                      CAST read law (ADR-0003 Am.1) is
                                      satisfied vacuously here; this
                                      golden guards that fact (a future
                                      TIMESTAMP declaration would change
                                      the DDL bytes and fail the schema
                                      test, forcing the CAST).

Usage (from the repo root):
    python3 testdiff/goldens/dump_notestate.py

Env overrides: GC_PYTHON / GC_APP_DIR (same conventions as ../harness.py).

No PyQt stub needed: core/note_state.py is pure stdlib by its own module
docstring ("importable from the CLI, tests and CI").
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")
DEFAULT_APP_DIR = os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app")

PAYLOAD = r'''
import hashlib, json, os, shutil, sqlite3, sys, tempfile
sys.path.insert(0, os.environ["GC_APP_DIR"])

from gitcurator.constants import CATEGORY_FOLDERS
from gitcurator.core.links import normalize_website_url
from gitcurator.core.note_state import NoteStateDB, compute_fingerprint, folder_category

OUT = os.environ["GOLDEN_OUT_DIR_NOTESTATE"]

def canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n"

def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)

def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()

stats = {}

# ---------------------------------------------------------------------------
# 1. The pure corpus — compute_fingerprint over fixed inputs (the STRIPPED
#    intermediate included: the recall-block non-greedy strip + rstrip law
#    is pinned directly, not just the hash) + the folder_category matrix.
# ---------------------------------------------------------------------------
RECALL_START = "<!-- gitcurator:recall:start -->"
RECALL_END = "<!-- gitcurator:recall:end -->"

FP_CASES = [
    # (name, kind, input) — kind 'str' (already text) or 'bytes' (decoded
    # utf-8 errors='replace' first, exactly like every reference file read).
    ("plain", "str", "abc"),
    ("unicode", "str", "héllo — 世界 🌍\r\n"),
    ("one_recall_block", "str",
     "note body\n" + RECALL_START + "\nrelated: something\n" + RECALL_END),
    ("two_recall_blocks", "str",
     "a" + RECALL_START + "x" + RECALL_END + "b" + RECALL_START + "y"
     + RECALL_END + "c"),
    ("unterminated_block", "str",
     "body\n" + RECALL_START + "\nnever closed\n"),
    ("trailing_whitespace", "str", "x  \n\n\t \r"),
    ("empty", "str", ""),
    ("only_block", "str", RECALL_START + "x" + RECALL_END),
    # The invalid-UTF-8 battery: byte inputs that must decode exactly like
    # the reference's own open(..., errors='replace') reads before the
    # strip+hash — pinning Python's replacement semantics byte-exact.
    ("invalid_single_ff", "bytes", b"\xff"),
    ("invalid_c2_then_ascii", "bytes", b"\xc2A"),
    ("invalid_truncated_e2_82", "bytes", b"a\xe2\x82"),
    ("invalid_run_c3_c3", "bytes", b"\xc3\xc3A"),
    ("invalid_mixed", "bytes", b"\xfe\xfftext\xc3\xbd"),
    ("valid_replacement_literal", "bytes", b"\xef\xbf\xbd"),
    # SESSION-008 — the CRLF law: the reference's text-mode read
    # translates \r\n to \n BEFORE the fingerprint (the owner's
    # Windows vault notes are CRLF; the untranslated bytes hash
    # differently — the port's readHead800 fidelity fix is pinned here)
    ("crlf_file_read", "bytes",
     b'---\r\nsource: "https://a.example/x"\r\n---\r\n\r\n# A Note\r\n\r\nbody text\r\n'),
]

import re
from gitcurator.core.note_state import _RECALL_BLOCK

fp_cases = []
for name, kind, payload in FP_CASES:
    if kind == "bytes":
        # model the reference's OWN file read exactly: text mode's
        # universal-newlines translation applies after the replace
        # decode (open(..., 'r', encoding='utf-8', errors='replace')
        # .read(800) — SESSION-008: the CRLF case pins it; a no-op for
        # every earlier byte case, none of which carries \r)
        text = payload.decode("utf-8", "replace").replace("\r\n", "\n").replace("\r", "\n")
        as_json = list(payload)
    else:
        text = payload
        as_json = payload
    stripped = _RECALL_BLOCK.sub('', text or '').rstrip()
    fp_cases.append({
        "name": name,
        "kind": kind,
        "input": as_json,
        "stripped": stripped,
        "sha256": hashlib.sha256(stripped.encode("utf-8", "replace")).hexdigest(),
    })

# The folder_category matrix: all 24 exact CATEGORY_FOLDERS hits + edges.
folders = sorted(CATEGORY_FOLDERS.values()) + [
    "", "_review", "/", "//_review//", "RandomFolder",
    "AI-Domain/Agents/Frameworks", "Tools/Scraping/Extras",
    "a/b\\c", " AI-Domain/Agents ", "AI-Domain", "AI-Domain/Nope/Deep",
]
fc_rows = []
for f in folders:
    cat, sub = folder_category(f)
    fc_rows.append([f, cat, sub])

pure = {"schema": 1, "fingerprint_cases": fp_cases, "folder_category": fc_rows}
write_text(os.path.join(OUT, "notestate_pure.golden.json"), canon(pure))
stats["fingerprint_cases"] = len(fp_cases)
stats["folder_category_rows"] = len(fc_rows)

# ---------------------------------------------------------------------------
# 2. THE PYTHON-CREATED FIXTURE — every write goes through the reference's
#    own NoteStateDB methods (never hand-typed SQL).
# ---------------------------------------------------------------------------
scratch = tempfile.mkdtemp(prefix="curator-notestate-")
db_path = os.path.join(scratch, "notestate_python_created.db")

ns = NoteStateDB(db_path)

# note_state — upserts incl. the update-in-place probe and a NULL-category
# (_review) row; the websites row carries a subcategory.
ns.upsert("github", "https://github.com/o/repo1",
          "/vault/AI-Domain/Agents/a.md", "f" * 64, "Agents", None, False)
ns.upsert("github", "https://github.com/o/repo2",
          "/vault/AI-Domain/Agents/Frameworks/b.md", "e" * 64,
          "Agents/Frameworks", None, False)
ns.upsert("github", "https://github.com/o/repo3",
          "/vault/_review/r.md", "d" * 64, None, None, False)
# update-in-place: same vault+source — path/fingerprint/locked refresh,
# first_seen must survive (the INSERT OR IGNORE half).
ns.upsert("github", "https://github.com/o/repo1",
          "/vault/Tools/Scraping/a.md", "c" * 64, "Scraping", None, True)
ns.upsert("websites", "https://example.com/site/",
          "/web/Design/UIUX/s.md", "b" * 64, "Design", "UI/UX", False)

# record_note — content given (fingerprint of the content, not the file);
# the websites normalizer probe (query-keeping key) + the GitHub default
# (normalize_url strips the trailing slash).
ns.record_note("websites", "https://example.com/page?utm_source=x",
               "/web/Design/Inspiration/p.md",
               content="---\nsource: x\n---\nbody\n",
               category="Design", subcategory="Inspiration",
               normalizer=normalize_website_url)
ns.record_note("github", "https://github.com/o/repo4/",
               "/vault/Tools/Scraping/c.md", content="content",
               category="Scraping")

# set_locked — updated_at refresh only.
ns.set_locked("github", "https://github.com/o/repo2", True)

# corrections_log — full call + the defaulted second call.
ns.log_correction("github", "https://github.com/o/repo1", "Agents",
                  "Scraping", "/vault/AI-Domain/Agents/a.md",
                  "/vault/Tools/Scraping/a.md", "owner moved")
ns.log_correction("github", "https://github.com/o/repo1", "Scraping", "MCP")
ns.log_correction("websites", "https://example.com/site/", "Design",
                  "Development", "/old", "/new", "recategorized")

# dismissed — insert + the INSERT OR REPLACE re-dismiss (still one row) +
# the clear_dismissed round-trip probes (True then False).
ns.dismiss("github", "https://github.com/o/gone", "/vault/old.md")
ns.dismiss("github", "https://github.com/o/gone", "")
clear_probe1 = ns.clear_dismissed("github", "https://github.com/o/scratch-never")
ns.dismiss("github", "https://github.com/o/scratch-never", "/vault/scr.md")
clear_probe2 = ns.clear_dismissed("github", "https://github.com/o/scratch-never")
clear_probe3 = ns.clear_dismissed("github", "https://github.com/o/scratch-never")
ns.dismiss("websites", "https://example.com/dead", "")

ns.close()

# ---------------------------------------------------------------------------
# 3. Read back through a FRESH reference open — raw columns (read-only
#    introspection) + the getter battery + pragma facts + schema.
# ---------------------------------------------------------------------------
ns2 = NoteStateDB(db_path)

pragma_facts = {
    "journal_mode":
        ns2.conn.execute("PRAGMA journal_mode").fetchone()[0],
    "busy_timeout":
        ns2.conn.execute("PRAGMA busy_timeout").fetchone()[0],
    "synchronous":
        ns2.conn.execute("PRAGMA synchronous").fetchone()[0],
}

TABLE_ORDER = [
    ("note_state", "id"),
    ("corrections_log", "id"),
    ("note_state_dismissed", "vault, source_url"),
]
tables = {}
for name, order_by in TABLE_ORDER:
    cur = ns2.conn.execute(f"SELECT * FROM {name} ORDER BY {order_by}")
    cols = [d[0] for d in cur.description]
    rows = [list(r) for r in cur.fetchall()]
    tables[name] = {"columns": cols, "rows": rows}

getters = {
    "count": {"github": ns2.count("github"),
              "websites": ns2.count("websites"),
              "absent-vault": ns2.count("nope")},
    "all_rows_github": ns2.all_rows("github"),
    "row_for": {
        u: ns2.row_for("github", u)
        for u in ("https://github.com/o/repo1",
                  "https://github.com/o/repo3",
                  "https://github.com/o/never")
    },
    "correction_count": {"github": ns2.correction_count("github"),
                         "websites": ns2.correction_count("websites")},
    "recent_corrections": ns2.recent_corrections("github", 2),
    "corrections_for": ns2.corrections_for("github",
                                           "https://github.com/o/repo1"),
    "dismissed_count": {"github": ns2.dismissed_count("github"),
                        "websites": ns2.dismissed_count("websites")},
    "dismissed_set": sorted(ns2.dismissed_set("github")),
    "is_dismissed": {
        u: ns2.is_dismissed("github", u)
        for u in ("https://github.com/o/gone",
                  "https://github.com/o/repo1")
    },
    "clear_dismissed_probes": [clear_probe1, clear_probe2, clear_probe3],
}

# The schema the reference's own __init__ produced (adopt-as-is law).
objects = [[r[0], r[1], r[2], r[3]]
           for r in ns2.conn.execute(
               "SELECT type, name, tbl_name, sql FROM sqlite_master "
               "ORDER BY type, name").fetchall()]
table_columns = {}
for name, _ in TABLE_ORDER:
    table_columns[name] = [
        [c[1], c[2], c[3], c[4], c[5]]
        for c in ns2.conn.execute(
            f"PRAGMA table_info({name})").fetchall()]

ns2.close()

no_sidecars = not os.path.exists(db_path + "-wal") \
          and not os.path.exists(db_path + "-shm")

# ---------------------------------------------------------------------------
# 4. Copy the fixture + write the goldens (fixture and content golden are
#    an ATOMIC PAIR: regeneration rewrites both together; the sha ties
#    them).
# ---------------------------------------------------------------------------
fixture_out = os.path.join(OUT, "notestate_python_created.db")
shutil.copyfile(db_path, fixture_out)

content = {
    "schema": 1,
    "fixture_sha256": sha(fixture_out),
    "no_sidecars_after_close": no_sidecars,
    "pragmas_through_reference": pragma_facts,
    "tables": tables,
    "getters": getters,
}
write_text(os.path.join(OUT, "notestate_fixture_content.golden.json"),
           canon(content))

schema_doc = {
    "schema": 1,
    "objects": objects,
    "table_columns": table_columns,
}
write_text(os.path.join(OUT, "notestate_schema.golden.json"), canon(schema_doc))

stats["fixture_sha256"] = content["fixture_sha256"]
stats["no_sidecars"] = no_sidecars
stats["pragmas"] = pragma_facts
stats["table_rows"] = {k: len(v["rows"]) for k, v in tables.items()}
stats["schema_objects"] = len(objects)

shutil.rmtree(scratch, ignore_errors=True)

print(json.dumps(stats))
'''


def main() -> int:
    out = REPO_ROOT / "internal" / "notestate" / "testdata"
    out.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "note_state.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_NOTESTATE"] = str(out)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/notestate testdata "
          f"({len(summary)} stat keys)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] fingerprint cases: {summary['fingerprint_cases']} "
          f"(folder_category rows: {summary['folder_category_rows']})")
    print(f"[goldens] fixture sha256: {summary['fixture_sha256']} "
          f"(clean close, no sidecars: {summary['no_sidecars']})")
    print(f"[goldens] pragmas through the reference's own open: "
          f"{summary['pragmas']}")
    print(f"[goldens] table rows: {summary['table_rows']}")
    print(f"[goldens] schema objects: {summary['schema_objects']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
