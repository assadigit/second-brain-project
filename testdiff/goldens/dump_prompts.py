#!/usr/bin/env python3
"""Golden generator for T-13 (internal/prompts + assets/prompts).

THE LAW: goldens are GENERATED by running the unmodified Python reference
app (assadigit/GitCurator @ 98f4fc7) — never hand-typed, never edited by
hand. This generator exercises core/prompts.py and dumps its behavior into
internal/prompts/testdata/, where the Go characterization tests
byte-compare their own port. It also COPIES the seven live prompt files
into assets/prompts/ (the go:embed source) straight from the reference —
the embed bytes are therefore generated artifacts, not hand-typed files.
The dead 01/02/03 prompts are deliberately NOT copied (spec-core-prompts.md
§inventory: no consumer; not shipped in Go).

What it pins (spec-core-prompts.md §Symbols / §Go notes & tests):

  assets/prompts/<7 live .txt>      verbatim copies from the reference
                                    (sha256-pinned in the golden below)

  internal/prompts/testdata/
    prompts_corpus.golden.json    slots_in corpus (order + dedupe + the
                                  {{SLOT}} grammar boundaries), fill_template
                                  successes (incl. non-str values, the BOM
                                  quirk NOT being stripped, partial markers
                                  passing the guard), every refusal error
                                  string byte-exact, ntpath.basename (the
                                  PRODUCTION platform's separator grammar;
                                  posixpath dumped alongside to document the
                                  rig divergence), Python repr() of the
                                  filename/path shapes the error messages
                                  embed, the missing-file message with the
                                  reference PROMPTS_DIR normalized to the
                                  Go virtual root "prompts/" (dump-time
                                  normalization per doc 09 §3 — reference
                                  install paths never enter goldens), and
                                  per-file facts (sha256, size, no-BOM,
                                  slots_in) for the 7 live prompt files.

Usage (from the repo root):
    python3 testdiff/goldens/dump_prompts.py

Env overrides: GC_PYTHON / GC_APP_DIR (same conventions as ../harness.py).
"""

import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")
DEFAULT_APP_DIR = os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app")

# The seven live prompt files (spec-core-prompts.md §Prompt inventory).
# 01_categorize / 02_summarize / 03_crosscheck are dead — NOT shipped.
LIVE_PROMPTS = [
    "l01_confirm.txt",
    "r01_recall.txt",
    "s01_vaultscan.txt",
    "s02_reposscan.txt",
    "w01_category.txt",
    "w02_subcategory.txt",
    "w03_analyze.txt",
]

PAYLOAD = r'''
import hashlib, json, os, shutil, sys, ntpath, posixpath

sys.path.insert(0, os.environ["GC_APP_DIR"])
from gitcurator.core import prompts as P

OUT_P = os.environ["GOLDEN_OUT_DIR_PROMPTS"]
ASSETS = os.environ["PROMPTS_ASSETS_DIR"]
LIVE = json.loads(os.environ["LIVE_PROMPTS_JSON"])

def canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n"

def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)

def sha_bytes(b):
    return hashlib.sha256(b).hexdigest()

def prompt_error(call):
    """Run call(); return the PromptError string, or "<no error: RESULT>"."""
    try:
        return "<no error: %r>" % (call(),)
    except P.PromptError as exc:
        return str(exc)

# ---------------------------------------------------------------------------
# 1. slots_in — the {{SLOT}} grammar: order, dedupe, boundaries.
# ---------------------------------------------------------------------------
SLOTS_PROBES = [
    "{{A}}",
    "{{A}} {{B}} {{A}}",            # dedupe keeps first position
    "{{A}} then {{AB}} then {{A_B2}}",
    "{{lower}}",                    # lowercase: not a slot
    "{{lower_case}}",               # lowercase with underscore: not a slot
    "{{1A}}",                       # leading digit: not a slot
    "{{A B}}",                      # space: not a slot
    "{{A-B}}",                      # dash: not a slot
    "{{}}",                         # empty: not a slot
    "{{}}{{A}}{{a}}",               # mixed: only A
    "no slots at all",
    "",                             # empty template
    "{{À}}",                        # non-ASCII letter: not a slot
    "{{A_}}{{_A}}",                 # underscore placement
    "prefix{{URL}}middle{{TITLE}}suffix",
]
slots_doc = [[t, P.slots_in(t)] for t in SLOTS_PROBES]
# None template: slots_in(None) → [] via `template or ''`
slots_doc.append([None, P.slots_in(None)])

# ---------------------------------------------------------------------------
# 2. fill_template — successes. Values kept JSON-shaped (order preserved as
#    a LIST of pairs — Python kwargs order is behavior).
# ---------------------------------------------------------------------------
FILL_OK = [
    # (template, [[name, value], ...])
    ("{{A}}", [["A", "x"]]),
    ("Hello {{NAME}} and {{OTHER}}", [["NAME", "x"], ["OTHER", "y"]]),
    ("{{A}} and {{A}} again", [["A", "dup"]]),          # repeated slot
    ("no slots here", [["A", "unused"]]),               # extra kwarg ignored
    ("{{A}}", [["A", 5]]),                              # int → str()
    ("{{A}}", [["A", 5.0]]),                            # float → "5.0"
    ("{{A}}", [["A", 2.5]]),
    ("{{A}}", [["A", 1e15]]),                           # positional repr
    ("{{A}}", [["A", 1e-05]]),                          # scientific repr
    ("{{A}}", [["A", True]]),                           # bool → "True"
    ("{{A}}", [["A", False]]),                          # bool → "False"
    ("{{A}}", [["A", 0]]),                              # 0 is NOT unfilled
    ("{{A}}", [["A", "0"]]),
    ("{{A}}", [["A", "你好 🗑️ — naïve"]]),              # unicode passthrough
    ("{{A}}", [["A", "{{partial"]]),                    # no closing }}: passes guard
    ("{{A}}", [["A", "{{9X}}"]]),                       # not slot-shaped: passes guard
    ("{{A}}", [["A", "has {{ bracket"]]),               # lone {{: passes guard
    ("﻿# {{A}}", [["A", "title"]]),                      # BOM quirk: NOT stripped
    ("", []),                                           # empty template, no values
    ("x", [["A", ""]]),                                 # empty value for NON-slot key: fine
]
fill_ok_doc = []
for template, pairs in FILL_OK:
    kwargs = {n: v for n, v in pairs}
    out = P.fill_template(template, **kwargs)
    fill_ok_doc.append([template, pairs, out])

# ---------------------------------------------------------------------------
# 3. fill_template — every refusal, byte-exact.
#    Note: value None FOR a declared slot hits the missing-check FIRST
#    (values[name] in (None, "")); "got None" only fires for non-slot keys.
# ---------------------------------------------------------------------------
FILL_ERRORS = [
    (None, []),                                          # no template given
    ("{{A}}", [["A", ""]]),                              # empty value
    ("Hello {{NAME}} and {{OTHER}}", [["NAME", "x"]]),   # missing OTHER
    ("{{B}} {{A}}", []),                                 # both, slots_in order
    ("x", [["A", None]]),                                # None for non-slot key
    ("{{A}}", [["A", None]]),                            # None for slot → unfilled first
    ("{{A}}", [["A", "{{B}}"]]),                         # marker smuggling
    ("{{A}}}}", [["A", "{{C"]]),                         # value builds a leftover slot
    ("{{A}}", [["A", "v"], ["B", "{{C}}"]]),             # smuggled via unused key
]
fill_errors_doc = []
for template, pairs in FILL_ERRORS:
    kwargs = {n: v for n, v in pairs}
    msg = prompt_error(lambda t=template, kw=kwargs: P.fill_template(t, **kw))
    fill_errors_doc.append([template, pairs, msg])

# ---------------------------------------------------------------------------
# 4. load_prompt_file — the filename grammar + read failures, byte-exact.
#    PRODUCTION platform for the reference app is Windows: os.path there is
#    ntpath, so the separator grammar (backslash, drive colon) is pinned
#    from ntpath.basename. posixpath is dumped alongside to document what
#    the Linux rig itself computes — the Go port pins the ntpath column
#    (platform-stable behavior == reference-on-Windows).
# ---------------------------------------------------------------------------
BAD_NAMES = [
    "../secrets.txt", "sub/file.txt", "a\\b.txt", "C:foo.txt", "C:\\x.txt",
    "a//b", "\\root", "..", ".", "", "a b.txt", "plain.txt",
    "w01_category.txt", "a:b.txt", "nul.txt",
]
ntbase_doc = [[n, ntpath.basename(n), ntpath.basename(n) == n] for n in BAD_NAMES]
posixbase_doc = [[n, posixpath.basename(n), posixpath.basename(n) == n] for n in BAD_NAMES]

# Dump-time normalization (doc 09 §3): the reference's PROMPTS_DIR (an
# absolute install path) → the Go virtual root "prompts" — reference paths
# never enter goldens; the Go side builds the same string from its
# embedded-FS root.
PROMPTS_DIR = P.PROMPTS_DIR
def norm_path(s):
    return s.replace(PROMPTS_DIR, "prompts")

bad_filename_errors = []
# Platform-INDEPENDENT bad names (rejected under both posixpath and ntpath,
# so the rig's messages are production-faithful). The platform-dependent
# names ('a\\b.txt', 'C:foo.txt', …) are pinned ONLY via the ntbasename
# corpus above — the rig runs posixpath, production runs ntpath.
for name in ["../secrets.txt", "", "sub/file.txt", "a//b"]:
    msg = prompt_error(lambda nm=name: P.load_prompt_file(nm, A="a"))
    bad_filename_errors.append([name, norm_path(msg)])

# missing files — same normalization.
missing_file_errors = []
for name in ["nope.txt", "w04_missing.txt"]:
    msg = prompt_error(lambda nm=name: P.load_prompt_file(nm, A="a"))
    missing_file_errors.append([name, norm_path(msg)])
# load_prompt (stem form) missing → same shape via stem + ".txt"
msg = prompt_error(lambda: P.load_prompt("no-such-stem", A="a"))
missing_file_errors.append(["no-such-stem.txt", norm_path(msg)])

# ---------------------------------------------------------------------------
# 5. Python repr() corpus — the error messages embed {x!r}; the Go port's
#    pyRepr is pinned byte-exact against these.
# ---------------------------------------------------------------------------
REPR_PROBES = [
    "../secrets.txt", "plain.txt", "a\\b", "C:\\x", "it's", 'say "hi"',
    "it's \"both\"", "tab\there", "nl\nhere", "cr\rhere", "\x00\x01\x1f\x7f",
    "你好", "é", "nbsp\xa0", "soft\xad", "U+2028 ", "", "x", "prompts/nope.txt",
]
pyrepr_doc = [[s, repr(s)] for s in REPR_PROBES]

# ---------------------------------------------------------------------------
# 6. The seven live prompt files: verbatim copy into assets/prompts/ +
#    derived facts (sha256, size, no-BOM flag, declared slots).
#    The w01/w02/w03 fills use the characterization slots from
#    app/tests/test_phase2.py TestPrompts.test_prompt_files_fill_completely.
# ---------------------------------------------------------------------------
files_doc = []
for name in LIVE:
    src = os.path.join(PROMPTS_DIR, name)
    with open(src, "rb") as f:
        raw = f.read()
    shutil.copyfile(src, os.path.join(ASSETS, name))
    template = raw.decode("utf-8")   # plain utf-8 — NOT -sig (the BOM quirk)
    files_doc.append([
        name,
        {
            "sha256": sha_bytes(raw),
            "bytes": len(raw),
            "has_bom": raw.startswith(b"\xef\xbb\xbf"),
            "slots": P.slots_in(template),
        },
    ])

W_FILLS = [
    ("w01_category", [
        ["CATEGORY_NAMES_WITH_ONE_LINE_DEFINITIONS", "- A\n- B"],
        ["JUDGMENT_RULES", "rules"],
        ["PAST_CORRECTIONS", "(none)"],
        ["URL", "https://x"],
        ["TITLE", "T"],
        ["META_DESCRIPTION", "D"],
        ["TEXT_EXCERPT", "E"],
    ]),
    ("w02_subcategory", [
        ["CATEGORY", "A"],
        ["SUBCATEGORIES_WITH_DEFINITIONS", "- s1"],
        ["URL", "https://x"],
        ["TITLE", "T"],
        ["META_DESCRIPTION", "D"],
        ["TEXT_EXCERPT", "E"],
    ]),
    ("w03_analyze", [
        ["TAG_HINTS", "#a #b"],
        ["URL", "https://x"],
        ["TITLE", "T"],
        ["META_DESCRIPTION", "D"],
        ["TEXT_EXCERPT", "E"],
    ]),
]
w_fill_doc = []
for stem, pairs in W_FILLS:
    kwargs = {n: v for n, v in pairs}
    out = P.load_prompt(stem, **kwargs)
    w_fill_doc.append([stem, pairs, out])

doc = {
    "schema": 1,
    "slots_in": slots_doc,
    "fill_ok": fill_ok_doc,
    "fill_errors": fill_errors_doc,
    "ntbasename": ntbase_doc,
    "posixbasename": posixbase_doc,
    "bad_filename_errors": bad_filename_errors,
    "missing_file_errors": missing_file_errors,
    "pyrepr": pyrepr_doc,
    "prompt_files": files_doc,
    "w_fill_outputs": w_fill_doc,
}
write_text(os.path.join(OUT_P, "prompts_corpus.golden.json"), canon(doc))

print(json.dumps({
    "live_files": len(LIVE),
    "slots_probes": len(slots_doc),
    "fill_ok": len(fill_ok_doc),
    "fill_errors": len(fill_errors_doc),
    "w_fills": [stem for stem, _ in W_FILLS],
    "prompts_dir": PROMPTS_DIR,
}))
'''


def main() -> int:
    out_p = REPO_ROOT / "internal" / "prompts" / "testdata"
    assets = REPO_ROOT / "assets" / "prompts"
    out_p.mkdir(parents=True, exist_ok=True)
    assets.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "prompts.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    for name in LIVE_PROMPTS:
        if not (app_dir / "prompts" / name).exists():
            sys.exit(f"[goldens] reference prompt file missing: {name}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    # Remove stale prompt copies in assets/prompts (e.g. a file that is no
    # longer live) so the embed source always mirrors the reference exactly.
    for stale in assets.glob("*.txt"):
        if stale.name not in LIVE_PROMPTS:
            stale.unlink()

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_PROMPTS"] = str(out_p)
    env["PROMPTS_ASSETS_DIR"] = str(assets)
    env["LIVE_PROMPTS_JSON"] = json.dumps(LIVE_PROMPTS)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/prompts/testdata + "
          f"assets/prompts ({summary['live_files']} live files)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] probes: slots_in={summary['slots_probes']} "
          f"fill_ok={summary['fill_ok']} fill_errors={summary['fill_errors']}")
    print(f"[goldens] w-fills: {', '.join(summary['w_fills'])}")
    print(f"[goldens] reference PROMPTS_DIR (normalized out of goldens): "
          f"{summary['prompts_dir']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
