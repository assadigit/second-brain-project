#!/usr/bin/env python3
"""Golden generator for T-12 (internal/storage + internal/dryrun).

THE LAW: goldens are GENERATED by running the unmodified Python reference
app (assadigit/GitCurator @ 98f4fc7) — never hand-typed, never edited by
hand. This generator exercises core/storage.py + core/dryrun.py and dumps
their behavior into the Go packages' testdata/ directories, where the Go
characterization tests byte-compare their own ports.

What it pins (spec-core-storage.md §Compatibility / §Tests):

  internal/storage/testdata/
    config_roundtrip.input.json   the round-trip input (the reference repo's
                                  committed app/config.example.json — a real
                                  config copy, placeholders only, no secrets)
    config_roundtrip.golden.json  Python's write_config_file bytes after
                                  json.load of the input (the T-12 acceptance
                                  round-trip: Go must produce these bytes)
    merge_existing.input.json     merge-config fixtures (authored, then
    merge_updates.input.json      round-tripped through the files so both
                                  sides parse identical trees)
    merge_result.golden.json      write_config_file(merge_config(existing,
                                  updates)) bytes — pins ORDER (Python dict
                                  insertion semantics), nested merges, the
                                  tuning-key only-defaulted law
    merge_defaults.golden.json    write_config_file(merge_config({}, updates))
                                  — pins the setdefault append order
    storage_corpus.golden.json    safe_filename traversal corpus,
                                  build_note_filename probes, unique_path
                                  probes over a deterministic tree, the
                                  os.path.splitext name grammar, and float
                                  repr probes (the encoder's Python-parity
                                  law)

  internal/dryrun/testdata/
    dryrun_entries.golden.json    a recorded battery via record() with FIXED
                                  path strings: full entries + summary() in
                                  first-seen order. Volatile fields are
                                  normalized AT DUMP TIME by the generator
                                  (the harness's documented rules, doc 09
                                  §3): entry['time'] HH:MM:SS → '<TS>'. The
                                  time FORMAT itself is pinned by the Go
                                  test's own format assertion.
    dryrun_report.golden.md       render_report_markdown of that battery
                                  (raw markdown; HH:MM:SS → <TS> and the
                                  `*Generated: ...*` line → *Generated: <TS>*
                                  at dump time — same rules)
    dryrun_report_empty.golden.md the no-entries branch (same normalization)
    dryrun_standin.golden.json    the filesystem stand-ins (makedirs /
                                  write_text / append_text / move / remove)
                                  and shadow_cache_path probes — derived
                                  facts only (sha256 equalities, notes,
                                  basenames): temp paths never enter goldens

Usage (from the repo root):
    python3 testdiff/goldens/dump_storage.py

Env overrides: GC_PYTHON / GC_APP_DIR (same conventions as ../harness.py).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")
DEFAULT_APP_DIR = os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app")

PAYLOAD = r'''
import hashlib, json, os, re, shutil, sys, tempfile

sys.path.insert(0, os.environ["GC_APP_DIR"])
from gitcurator.core import storage as S, dryrun as D

OUT_S = os.environ["GOLDEN_OUT_DIR_STORAGE"]
OUT_D = os.environ["GOLDEN_OUT_DIR_DRYRUN"]

# The harness's documented normalizations (doc 09 §3), applied at DUMP TIME
# so the goldens stay byte-stable across regenerations for a pinned rev:
#   timestamp       HH:MM:SS        → <TS>
#   timestamp-iso   the Generated: line → *Generated: <TS>*
# The Go test applies the same rules to its own output before comparing
# (and pins the real formats with its own assertions).
def norm_ts(s):
    return re.sub(r"\d{2}:\d{2}:\d{2}", "<TS>", s)

def norm_generated_line(s):
    return re.sub(r"\*Generated: [^*]*\*", "*Generated: <TS>*", s)

def canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n"

def write_bytes(path, data):
    with open(path, "wb") as f:
        f.write(data)

def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)

def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()

def base(p):
    return os.path.basename(p)

scratch = tempfile.mkdtemp(prefix="curator-golden-")
stats = {}

# ---------------------------------------------------------------------------
# 1. The config round-trip (T-12 acceptance) on a REAL config copy — the
#    reference repo's committed app/config.example.json (placeholders only).
# ---------------------------------------------------------------------------
src_cfg = os.path.join(os.environ["GC_APP_DIR"], "config.example.json")
with open(src_cfg, encoding="utf-8") as f:
    config = json.load(f)
write_bytes(os.path.join(OUT_S, "config_roundtrip.input.json"),
            open(src_cfg, "rb").read())
rt_path = os.path.join(scratch, "config.json")
S.write_config_file(rt_path, config)
with open(rt_path, "rb") as f:
    rt_bytes = f.read()
write_bytes(os.path.join(OUT_S, "config_roundtrip.golden.json"), rt_bytes)
stats["roundtrip_bytes"] = len(rt_bytes)
stats["roundtrip_equals_input"] = rt_bytes == open(src_cfg, "rb").read()

# ---------------------------------------------------------------------------
# 2. merge_config — the ordered law. Fixtures are authored here, written to
#    the input files, then LOADED BACK so Python and Go parse identical
#    trees; the goldens are the write_config_file bytes of the merges.
# ---------------------------------------------------------------------------
MERGE_EXISTING = {
    "ollama": {"base_url": "http://localhost:11434", "model": "old",
               "custom_key": "keep-me"},
    "proxy": {"host": "127.0.0.1", "port": 10808},
    "timeout_per_repo": 120,
    "max_retries": 7,
    "delay_between_api_calls": 2.5,
    "cloudflare_install_id": "uuid-123",
    "cloudflare_shared_secret": "abc",
    "gdrive_folder_id": "xyz",
    "user_added_key": 42,
    "unicode_key_value": "标签 — with em-dash · naïve résumé",
    "list_val": [1, 2, 3],
    "scalar_to_dict": "old-scalar",
    "dict_to_scalar": {"a": 1},
}
MERGE_UPDATES = {
    "ollama": {"model": "new-model", "extra_nested": "new"},
    "proxy": {"port": 10809, "user": "me"},
    "brand_new_top": {"one": 1},
    "scalar_to_dict": {"now": "a-dict"},
    "dict_to_scalar": "now-a-scalar",
    "list_val": [9, 8],
    "unicode_key_value": "更新 — updated value",
}
for name, doc in (("merge_existing.input.json", MERGE_EXISTING),
                  ("merge_updates.input.json", MERGE_UPDATES)):
    write_text(os.path.join(OUT_S, name),
               json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
with open(os.path.join(OUT_S, "merge_existing.input.json"), encoding="utf-8") as f:
    existing = json.load(f)
with open(os.path.join(OUT_S, "merge_updates.input.json"), encoding="utf-8") as f:
    updates = json.load(f)

merged = S.merge_config(existing, updates)
p = os.path.join(scratch, "merged.json")
S.write_config_file(p, merged)
write_bytes(os.path.join(OUT_S, "merge_result.golden.json"), open(p, "rb").read())
stats["merge_keys"] = list(merged.keys())

merged_defaults = S.merge_config({}, updates)
p = os.path.join(scratch, "defaults.json")
S.write_config_file(p, merged_defaults)
write_bytes(os.path.join(OUT_S, "merge_defaults.golden.json"), open(p, "rb").read())
stats["defaults_keys"] = list(merged_defaults.keys())

# ---------------------------------------------------------------------------
# 3. storage corpus — safe_filename / build_note_filename / unique_path /
#    os.path.splitext / float repr (the encoder law).
# ---------------------------------------------------------------------------
SAFE_FILENAME = [
    "../../etc/passwd", "a/b\\c..d", "my.repo-name_2", "AI & ML",
    "数据科学", "🎬-emoji", "..", "", ".", "a  b", "ünïcödé",
    "tags[0]", "with\nnewline", "a---b", "-_-", "start/end:here",
]
BUILD_NOTE = [
    ["my.repo", "AI & ML", ["llm", "x"]],
    ["r", "c", []],
    ["r", "c", [""]],
    ["数据/仓库", "Infrastructure/Cloud", ["tag one"]],
    ["../evil", "Agents", ["pwn/me"]],
]

up_scratch = tempfile.mkdtemp(prefix="curator-up-")
# A deterministic collision tree: note.md exists -> _v1; both exist -> _v2.
with open(os.path.join(up_scratch, "note.md"), "w") as f:
    f.write("first")
u1 = S.unique_path(os.path.join(up_scratch, "note.md"))
with open(u1, "w") as f:
    f.write("second")
u2 = S.unique_path(os.path.join(up_scratch, "note.md"))
with open(os.path.join(up_scratch, "file"), "w") as f:
    f.write("x")
u3 = S.unique_path(os.path.join(up_scratch, "file"))
with open(os.path.join(up_scratch, ".hidden"), "w") as f:
    f.write("x")
u4 = S.unique_path(os.path.join(up_scratch, ".hidden"))
u5 = S.unique_path(os.path.join(up_scratch, "fresh.md"))  # absent -> itself
UNIQUE_PATH = [[base(p), base(r)] for p, r in [
    (os.path.join(up_scratch, "note.md"), u1),
    (os.path.join(up_scratch, "note.md"), u2),
    (os.path.join(up_scratch, "file"), u3),
    (os.path.join(up_scratch, ".hidden"), u4),
    (os.path.join(up_scratch, "fresh.md"), u5),
]]

SPLITEXT = [
    "note.md", "archive.tar.gz", "file", ".hidden", ".env.local", "a.",
    "a.b/c", "", "no_ext.", "x.json.bak", "..dots", "a b.txt",
]
FLOAT_PROBES = [0.5, 2.0, 1e15, 1e16, 1e-05, 1.2345678901234568e+17,
                0.0001, 3.141592653589793, 1234.5, 1e100, -2.5, 60, 3]

doc = {
    "schema": 1,
    "safe_filename": [[s, S.safe_filename(s)] for s in SAFE_FILENAME],
    "build_note_filename": [[r, c, t, S.build_note_filename(r, c, t)]
                            for r, c, t in BUILD_NOTE],
    "unique_path": UNIQUE_PATH,
    "splitext": [[n, list(os.path.splitext(n))] for n in SPLITEXT],
    "float_repr": [[f, json.dumps(f)] for f in FLOAT_PROBES],
}
write_text(os.path.join(OUT_S, "storage_corpus.golden.json"), canon(doc))
stats["safe_filename"] = len(SAFE_FILENAME)

# ---------------------------------------------------------------------------
# 4. dryrun record battery — FIXED path strings only (record() never touches
#    the disk), so entries are fully deterministic except `time`. Every
#    preview rule gets a probe: newline→⏎, \r-strip, the 160-char cap with
#    '…', the 160-BYTE cut mid-rune (no '…' — preserved quirk), invalid
#    UTF-8 → U+FFFD per maximal subpart, empty, and size None.
# ---------------------------------------------------------------------------
D.enable()
D.clear()
BATTERY = [
    # (op, path, content, note) — content strings/bytes verbatim
    ("write", "/vault/Notes/note.md",
     "# Title\r\n\nBody — émoji 🗑️ and | pipe\n", ""),
    ("append", "/vault/Notes/note.md", "more text", ""),
    ("write", "/vault/Notes/long.md", "x" * 300, ""),
    ("write", "/vault/Notes/cjk-str.md", "数" * 200, ""),
    ("write", "/vault/Notes/cjk-bytes.md", "阿".encode("utf-8") * 200, ""),
    ("banner", "/vault/banner.png",
     b"\x89PNG\r\n\x1a\n" + b"\xff\xfe" + b"y" * 300, ""),
    ("makedirs", "/vault/Notes", None, "create folder"),
    ("move", "/vault/Notes/new.md", None, "from /vault/Notes/old.md"),
    ("remove", "/vault/Notes/old.md", None, "delete file"),
    ("write", "/vault/Notes/empty.md", "", ""),
    ("append", "/vault/Notes/empty-bytes.db", b"", ""),
    ("write", "/vault/Notes/just-under.md", "y" * 159, ""),
    ("write", "/vault/Notes/exact.md", "z" * 160, ""),
]
for op, path, content, note in BATTERY:
    D.record(op, path, content=content, note=note)

entries_doc = {
    "schema": 1,
    "entries": [dict(e, time=norm_ts(e["time"])) for e in D.entries()],
    "summary_ordered": [[op, n] for op, n in D.summary().items()],
}
write_text(os.path.join(OUT_D, "dryrun_entries.golden.json"), canon(entries_doc))
report = norm_generated_line(norm_ts(D.render_report_markdown("Dry-run report")))
write_text(os.path.join(OUT_D, "dryrun_report.golden.md"), report)
D.clear()
write_text(os.path.join(OUT_D, "dryrun_report_empty.golden.md"),
           norm_generated_line(
               norm_ts(D.render_report_markdown("Dry-run report"))))
D.disable()
D.clear()
stats["battery_entries"] = len(entries_doc["entries"])

# ---------------------------------------------------------------------------
# 5. dryrun stand-ins + shadow cache — derived facts only (temp paths never
#    enter goldens). Includes the two preserved quirks: disable()'s dead
#    cleanup (temp dir SURVIVES) and enable() NOT resetting _shadow_dir
#    (double-enable reuses the same dir).
# ---------------------------------------------------------------------------
st_scratch = tempfile.mkdtemp(prefix="curator-standin-")
os.makedirs(os.path.join(st_scratch, "exists"))  # raw, before enabling

D.enable()
D.clear()
D.makedirs(os.path.join(st_scratch, "exists"))          # 'folder exists'
D.makedirs(os.path.join(st_scratch, "new-folder"))      # 'create folder'
D.write_text(os.path.join(st_scratch, "w.txt"), "hello")
D.append_text(os.path.join(st_scratch, "w.txt"), "!")
D.move(os.path.join(st_scratch, "a.md"), os.path.join(st_scratch, "b.md"))
D.remove(os.path.join(st_scratch, "a.md"))
# paths of makedirs/write/... are real scratch paths (random); keep only
# deterministic fields ([op, note, size, preview]) with the harness's
# temp-path rule applied to notes (move's note embeds the random src path).
def norm_note(note):
    return note.replace(st_scratch, "<TMP>")

standin = [[e["op"], norm_note(e["note"]), e["size"], e["preview"]]
           for e in D.entries()]
D.disable()
D.clear()

# --- shadow cache: real source with WAL sidecars --------------------------
sh_scratch = tempfile.mkdtemp(prefix="curator-shadow-")
real_db = os.path.join(sh_scratch, "cache.db")
with open(real_db, "wb") as f:
    f.write(b"REAL-CACHE-" + b"0123456789abcdef" * 64)
with open(real_db + "-wal", "wb") as f:
    f.write(b"WAL-" + b"\x00\x01\x02" * 33)
with open(real_db + "-shm", "wb") as f:
    f.write(b"SHM-" + b"\xff" * 100)

D.enable()
D.clear()
sh1 = D.shadow_cache_path(real_db)
sh1_dir = os.path.dirname(sh1)
shadow_real = {
    "basename": base(sh1),
    "dir_prefix_ok": base(sh1_dir).startswith("gitcurator-dryrun-"),
    "shadow_sha_eq": sha(sh1) == sha(real_db),
    "wal_sha_eq": sha(sh1 + "-wal") == sha(real_db + "-wal"),
    "shm_sha_eq": sha(sh1 + "-shm") == sha(real_db + "-shm"),
    "mtime_equal": os.path.getmtime(sh1) == os.path.getmtime(real_db),
    "recorded_ops": [e["op"] for e in D.entries()],  # copy OK -> none
}
# second call in the same enable-session -> SAME path (cached)
shadow_real["second_call_same"] = D.shadow_cache_path(real_db) == sh1

# missing source -> info entry; usable path
D.disable()
D.clear()
D.enable()
missing = os.path.join(sh_scratch, "does-not-exist.db")
sh2 = D.shadow_cache_path(missing)
info_entries = [e for e in D.entries() if e["op"] == "info"]
shadow_missing = {
    "basename": base(sh2),
    "info_note": info_entries[0]["note"] if info_entries else None,
    "info_count": len(info_entries),
}

# the double-enable quirk: enable() does NOT reset _shadow_dir — a second
# enable reuses the SAME temp dir (documented preserved quirk; cleanup only
# happens via disable()'s dead call).
sh2_dir = os.path.dirname(sh2)
D.enable()
sh3 = D.shadow_cache_path(missing)
shadow_double_enable = {
    "same_dir": os.path.dirname(sh3) == sh2_dir,
    "same_path": sh3 == sh2,
}
D.disable()
D.clear()

# the disable() dead-cleanup quirk: the temp dir SURVIVES disable() (the
# cleanup call reads the already-None global). Deterministic fact: the dir
# still exists after disable.
shadow_cleanup_quirk = {"dir_survives_disable": os.path.isdir(sh2_dir)}

doc = {
    "schema": 1,
    "standin_on": standin,
    "shadow_real": shadow_real,
    "shadow_missing": shadow_missing,
    "shadow_double_enable": shadow_double_enable,
    "shadow_cleanup_quirk": shadow_cleanup_quirk,
}
write_text(os.path.join(OUT_D, "dryrun_standin.golden.json"), canon(doc))

stats["standin_ops"] = len(standin)
stats["shadow_real"] = shadow_real
stats["shadow_missing_info"] = shadow_missing["info_note"]

shutil.rmtree(scratch, ignore_errors=True)
shutil.rmtree(up_scratch, ignore_errors=True)
shutil.rmtree(st_scratch, ignore_errors=True)
shutil.rmtree(sh_scratch, ignore_errors=True)

print(json.dumps(stats))
'''


def main() -> int:
    out_s = REPO_ROOT / "internal" / "storage" / "testdata"
    out_d = REPO_ROOT / "internal" / "dryrun" / "testdata"
    out_s.mkdir(parents=True, exist_ok=True)
    out_d.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "storage.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    if not (app_dir / "config.example.json").exists():
        sys.exit(f"[goldens] reference config.example.json not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_STORAGE"] = str(out_s)
    env["GOLDEN_OUT_DIR_DRYRUN"] = str(out_d)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated storage/ + dryrun/ testdata "
          f"({len(summary)} stat keys)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] round-trip: {summary['roundtrip_bytes']} bytes "
          f"(equals input file: {summary['roundtrip_equals_input']})")
    print(f"[goldens] merge order: {summary['merge_keys']}")
    print(f"[goldens] defaults order: {summary['defaults_keys']}")
    print(f"[goldens] battery entries: {summary['battery_entries']}; "
          f"stand-ins: {summary['standin_ops']}")
    print(f"[goldens] shadow real: {summary['shadow_real']}")
    print(f"[goldens] shadow missing info: {summary['shadow_missing_info']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
