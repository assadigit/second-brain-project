def dump_db():
    """Timestamp-free row dumps: the *_at columns are T-23's own
    golden's territory (websitestate_pure.golden.json pins them); this
    golden pins the pipeline's ledger EFFECTS (urls, reasons, paths,
    verdicts) — every fact here is frozen-dated or timeless."""
    import sqlite3
    con = sqlite3.connect(DB_PATH)
    out = {}
    out["dismissed"] = sorted(
        (r[0], r[1]) for r in con.execute(
            "SELECT url, reason FROM dismissed_urls"))
    out["processed"] = sorted(
        (r[0], r[1], r[2]) for r in con.execute(
            "SELECT url, note_path, fetch_status FROM websites_processed"))
    out["retry"] = sorted(
        (r[0], r[1], r[2]) for r in con.execute(
            "SELECT url, attempts, last_error FROM website_retry_queue"))
    out["settled"] = sorted(
        r[0] for r in con.execute("SELECT url FROM websites_settled"))
    out["meta"] = sorted(
        (r[0], r[1]) for r in con.execute(
            "SELECT key, value FROM website_state_meta"))
    con.close()
    return out


