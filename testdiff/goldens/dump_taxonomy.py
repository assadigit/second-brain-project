def main() -> int:
    out_t = REPO_ROOT / "internal" / "taxonomy" / "testdata"
    assets = REPO_ROOT / "assets" / "taxonomy"
    out_t.mkdir(parents=True, exist_ok=True)
    assets.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    fixture = app_dir / "tests" / "fixtures" / "website-library-categories.md"
    shipped = app_dir / "taxonomy" / "website-library-categories.md"
    if not (app_dir / "gitcurator" / "core" / "taxonomy.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    if not fixture.exists():
        sys.exit(f"[goldens] reference fixture missing: {fixture}")
    if not shipped.exists():
        sys.exit(f"[goldens] reference shipped taxonomy missing: {shipped}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_TAXONOMY"] = str(out_t)
    env["TAXONOMY_ASSETS_DIR"] = str(assets)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/taxonomy/testdata + "
          f"assets/taxonomy ({summary['grammar_probes']} grammar probes)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] fixture: {summary['fixture_categories']} categories / "
          f"{summary['fixture_subcategories']} subcategories")
    print(f"[goldens] shipped: {summary['shipped_categories']} categories / "
          f"{summary['shipped_subcategories']} subcategories")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
