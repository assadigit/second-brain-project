#!/usr/bin/env python3
"""Golden generator for T-14 (internal/taxonomy + assets/taxonomy).

THE LAW: goldens are GENERATED by running the unmodified Python reference
app (assadigit/GitCurator @ 98f4fc7) — never hand-typed, never edited by
hand. This generator exercises core/taxonomy.py and dumps its behavior
into internal/taxonomy/testdata/, where the Go characterization tests
byte-compare their own port. It also COPIES two taxonomy files as
generated artifacts:

  internal/taxonomy/testdata/website-library-categories.md
      the reference's OWN characterization fixture
      (app/tests/fixtures/website-library-categories.md — the pinned
      14-category/16-subcategory input test_phase2 asserts against)
  assets/taxonomy/website-library-categories.md
      the SHIPPED taxonomy (app/taxonomy/…; 14/23 parse snapshot) —
      embedded per doc 04 §1's assets layout; the parity loaders stay
      disk-based (Python behavior)

What the golden pins (spec-core-taxonomy.md §Parsing grammar / §Tests):

  taxonomy_corpus.golden.json
    fixture_model       the fully parsed fixture model in order:
                        per category name/definition/subcategories/
                        subcategory_definitions/tag_hints, plus
                        judgment_rules and summary()
    fixture_queries     category_one_liner, subcategory_one_liner per
                        category, tag_hints_of per category,
                        is_category/is_subcategory_of validation probes
                        (exact match; whitespace tolerated, case not),
                        category() unknown → null, subcategories_of
                        unknown → []
    folder_relpaths     safe_filename mapping probes via os.path.join
                        (platform separator — the Go port mirrors
                        os.sep per-platform like os.path.join itself)
    errors              every TaxonomyError message byte-exact: no
                        headings, heading-without-name (repr'd line),
                        duplicate category, unknown category/subcategory
                        (repr'd args), unreadable file (path normalized
                        out — dump-time doc 09 §3), and the
                        UnicodeDecodeError escape on invalid UTF-8
                        (NOT a TaxonomyError in Python — type pinned)
    bom                 a BOM'd file parses cleanly via utf-8-sig
                        (load taxonomy strips it) — the parsed names
    grammar             synthetic mini-taxonomies, one per parser rule:
                        emoji headings, trailing italic notes, em/en-dash
                        splits, (no subcategories) in bullet/prose/pure
                        marker shapes, "(empty for now" bullets, Example
                        tags lines (case-insensitive, multiple, appended),
                        ignored sections, judgment-rules section (bullets,
                        prose, *( prefix skipped), stray top-level lines,
                        ---, the italic-note-then-prose overwrite quirk,
                        duplicate subcategory bullets (deduped)
    shipped_snapshot    the shipped file's parse: ordered names, per-cat
                        subcategory counts, judgment_rules, sha256 of both
                        copied files
    splitlines          str.splitlines() boundary corpus (\\n \\r \\r\\n
                        \\v \\f \\x1c-\\x1e \\x85 U+2028 U+2029) pinning
                        the Go pySplitLines
    stripws             str.strip()/rstrip() Unicode-whitespace corpus
                        (U+00A0, \\x1c, U+2028 …) pinning the Go pyStrip

Usage (from the repo root):
    python3 testdiff/goldens/dump_taxonomy.py

Env overrides: GC_PYTHON / GC_APP_DIR (same conventions as ../harness.py).
"""

