doc["shipped_snapshot"] = shipped
write_text(os.path.join(OUT_T, "taxonomy_corpus.golden.json"), canon(doc))
stats["shipped_categories"] = len(stax.categories)
stats["shipped_subcategories"] = sum(len(c.subcategories)
                                     for c in stax.categories)
stats["grammar_probes"] = len(grammar)

shutil.rmtree(scratch, ignore_errors=True)
print(json.dumps(stats))
