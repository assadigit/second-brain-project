# --- the DBCS acceptance bitmaps --------------------------------------------
# x/text's decoders accept more than Python's codecs (its Big5 rides the
# WHATWG extension leads; its ShiftJIS maps 0x80) and gb18030's 4-byte
# piecewise gaps decode to FFFD-resync in x/text — so the port gates every
# DBCS decode on acceptance bitmaps GENERATED from Python itself (which
# sequences decode, decided by the len==1 disambiguation: a pair decodes
# to ONE character iff the first byte was a real lead).
import base64
def bits_to_b64(bits):
    n = (len(bits) + 7) // 8
    out = bytearray(n)
    for i, v in enumerate(bits):
        if v:
            out[i // 8] |= 1 << (i % 8)
    return base64.b64encode(bytes(out)).decode("ascii")

DBCS = ["big5", "shift_jis", "gbk", "gb2312", "gb18030", "euc-jp", "euc-kr"]
dbcs_accept = {}
for cs in DBCS:
    singles = [False] * 256
    for b in range(256):
        try:
            bytes([b]).decode(cs)
            singles[b] = True
        except UnicodeDecodeError:
            pass
    pairs = [False] * (128 * 256)
    for lead in range(0x80, 0x100):
        for trail in range(0x100):
            try:
                if len(bytes([lead, trail]).decode(cs)) == 1:
                    pairs[(lead - 0x80) * 256 + trail] = True
            except UnicodeDecodeError:
                pass
    entry = {
        "singles": bits_to_b64(singles),
        "pairs": bits_to_b64(pairs),
    }
    if cs == "euc-jp":
        triples = [False] * (128 * 256)
        for b2 in range(0x80, 0x100):
            for b3 in range(0x100):
                try:
                    if len(bytes([0x8F, b2, b3]).decode(cs)) == 1:
                        triples[(b2 - 0x80) * 256 + b3] = True
                except UnicodeDecodeError:
                    pass
        entry["triples"] = bits_to_b64(triples)
    dbcs_accept[cs] = entry
