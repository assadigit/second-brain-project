    entry = {"probes": {}}
    for bname, body in LADDER_BODIES.items():
        res = try_decode(body, name)
        if res is None:
            try:
                body.decode(name)
                entry["probes"][bname] = "ok"
            except LookupError:
                entry["probes"][bname] = "LookupError"
            except UnicodeDecodeError:
                entry["probes"][bname] = "UnicodeDecodeError"
        else:
            entry["probes"][bname] = "ok:" + res
    try:
        entry["full256"] = bytes(range(256)).decode(name)
    except UnicodeDecodeError:
        entry["full256"] = None
        holes = []
        for b in range(256):
            try:
                bytes([b]).decode(name)
            except UnicodeDecodeError:
                holes.append(b)
        entry["hole_count"] = len(holes)
        entry["holes_first16"] = holes[:16]
    except LookupError:
        entry["full256"] = None
        entry["hole_count"] = None
        entry["holes_first16"] = None
    ladder[name] = entry
