#!/usr/bin/env python3
"""goldens — generators for Go-side golden testdata.

THE LAW (NEXT-SESSION.md / roadmap Phase 1): goldens are GENERATED by running
the UNMODIFIED Python reference app (assadigit/GitCurator, pinned rev in
../PINNED-GITCURATOR-REV) — never hand-typed, never edited by hand.

Each generator dumps a section of the reference app's behavior as canonical
JSON (sort_keys=True, ensure_ascii=False, indent=2, trailing newline) into
the Go package's testdata/ directory, where the Go characterization test
byte-compares its own port against the golden.

Usage (from the repo root):

    python3 testdiff/goldens/dump_constants.py [--out PATH]

Environment overrides (same conventions as ../harness.py):
    GC_PYTHON   python that runs the reference app
                (default /home/z/venvs/gitcurator/bin/python)
    GC_APP_DIR  the reference app directory (default /home/z/GitCurator/app)

The generated file records the reference git rev on stdout (not inside the
golden: the golden must stay byte-stable for a pinned rev).
"""

import json
import os
import subprocess
import sys
from pathlib import Path

HARNESS_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = HARNESS_DIR.parent
PINNED_REV = (HARNESS_DIR / "PINNED-GITCURATOR-REV").read_text().strip()

DEFAULT_PY = os.environ.get("GC_PYTHON", "/home/z/venvs/gitcurator/bin/python")
DEFAULT_APP_DIR = os.environ.get("GC_APP_DIR", "/home/z/GitCurator/app")

# The payload executed BY the reference python (unmodified app on sys.path).
# Dumps constants.py symbols as two standalone canonical JSON documents:
#   config_example  — the full CONFIG_EXAMPLE dict (sorted keys)
#   symbols         — everything else (ordered category structures, colors,
#                     scalars, resolve_taxonomy_path probes, the prompt)
# Path-valued symbols are recorded RELATIVE to APP_DIR so the Go side (whose
# AppDir differs per test run) can compare portably.
PAYLOAD = r'''
import json, os, sys
sys.path.insert(0, os.environ["GC_APP_DIR"])
from gitcurator import constants as c

def canon(obj):
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, indent=2) + "\n"

def rel(p):
    # Normalize separators so the golden is platform-stable (Windows regen
    # would otherwise produce backslashes and diverge from the pinned bytes).
    return os.path.relpath(p, c.APP_DIR).replace(os.sep, "/")

probes = [
    {"config": None, "returned_rel": rel(c.resolve_taxonomy_path(None))},
    {"config": {}, "returned_rel": rel(c.resolve_taxonomy_path({}))},
    {"config": {"taxonomy_path": ""}, "returned_rel": rel(c.resolve_taxonomy_path({"taxonomy_path": ""}))},
    {"config": {"taxonomy_path": "   "}, "returned_rel": rel(c.resolve_taxonomy_path({"taxonomy_path": "   "}))},
    {"config": {"taxonomy_path": "/abs/override/x.md"}, "returned": c.resolve_taxonomy_path({"taxonomy_path": "/abs/override/x.md"})},
    {"config": {"taxonomy_path": "  /abs/override/y.md  "}, "returned": c.resolve_taxonomy_path({"taxonomy_path": "  /abs/override/y.md  "})},
]

symbols = {
    "schema": 1,
    "category_folders_ordered": [[k, v] for k, v in c.CATEGORY_FOLDERS.items()],
    "category_keys_ordered": list(c.CATEGORY_KEYS),
    "colors": c.COLORS,
    "scalars": {
        "managed_by_gitcurator": c.MANAGED_BY_GITCURATOR,
        "note_schema_version": c.NOTE_SCHEMA_VERSION,
        "github_prompt_version": c.GITHUB_PROMPT_VERSION,
        "ownership_banner": c.OWNERSHIP_BANNER,
        "expected_worker_version": c.EXPECTED_WORKER_VERSION,
        "config_file_rel": rel(c.CONFIG_FILE),
        "default_taxonomy_path_rel": rel(c.DEFAULT_TAXONOMY_PATH),
    },
    "resolve_taxonomy_path": probes,
    "default_system_prompt": c.DEFAULT_SYSTEM_PROMPT,
}

out_dir = os.environ["GOLDEN_OUT_DIR"]
with open(os.path.join(out_dir, "config_example.golden.json"), "w", encoding="utf-8") as f:
    f.write(canon(c.CONFIG_EXAMPLE))
with open(os.path.join(out_dir, "symbols.golden.json"), "w", encoding="utf-8") as f:
    f.write(canon(symbols))

print(json.dumps({
    "app_dir": c.APP_DIR,
    "config_example_top_level_keys": len(c.CONFIG_EXAMPLE),
    "category_folders": len(c.CATEGORY_FOLDERS),
    "colors": len(c.COLORS),
    "blocked_domains": len(c.CONFIG_EXAMPLE["web_blocked_domains"]),
}))
'''


def reference_rev(app_dir: str) -> str:
    try:
        proc = subprocess.run(
            ["git", "-C", str(Path(app_dir).parent), "rev-parse", "HEAD"],
            capture_output=True, text=True)
        if proc.returncode == 0:
            return proc.stdout.strip()
    except OSError:
        pass
    return "unknown"


def main() -> int:
    out_default = REPO_ROOT / "internal" / "constants" / "testdata"
    args = sys.argv[1:]
    out_dir = out_default
    if args[:2] == ["--out"]:
        out_dir = Path(args[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "constants.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = reference_rev(str(app_dir))
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR"] = str(out_dir)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                           capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated {out_dir}/config_example.golden.json + "
          f"symbols.golden.json")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] CONFIG_EXAMPLE: {summary['config_example_top_level_keys']} "
          f"top-level keys; {summary['blocked_domains']} blocked domains; "
          f"{summary['category_folders']} category folders; "
          f"{summary['colors']} color tokens")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
