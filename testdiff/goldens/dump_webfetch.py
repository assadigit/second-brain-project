ROOTS = {}


def normalize(text, extra_ports=()):
    if not isinstance(text, str):
        return text
    for port, tag in ROOTS.items():
        text = text.replace(f"http://127.0.0.1:{port}", f"<{tag}>")
        text = text.replace(f"127.0.0.1:{port}", f"<{tag}-RAW>")
    for port in extra_ports:
        text = text.replace(f"127.0.0.1:{port}", "<DEADPORT>")
    return text


def norm_res(res, keep_text=True, extra_ports=()):
    d = res_to_dict(res, keep_text=keep_text)
    if d is None:
        return None
    d["url"] = normalize(d["url"], extra_ports)
    d["final_url"] = normalize(d["final_url"], extra_ports)
    d["reason"] = normalize(d["reason"], extra_ports)
    if keep_text:
        d["text"] = normalize(d["text"], extra_ports)
    return d


def norm_request(req, extra_ports=()):
    return {
        "method": req["method"],
        "path": req["path"],
        "headers": [[k, normalize(v, extra_ports)]
                    for k, v in req["headers"]],
    }

