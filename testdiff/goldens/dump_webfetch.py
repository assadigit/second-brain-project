class WireRecorder(BaseHTTPRequestHandler):
    """Captures method, path, the ORDERED header pairs, body."""

    def _capture(self, body=b""):
        hdrs = [[k, v] for k, v in self.headers.items()]
        self.server.requests.append({
            "method": self.command,
            "path": self.path,
            "headers": hdrs,
            "body": body.decode("utf-8", "replace"),
        })

    def _reply(self, code, payload=b"", headers=None):
        self.send_response(code)
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        if payload or (headers or {}).get("Content-Type"):
            self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        if payload:
            self.wfile.write(payload)

    def do_GET(self):
        self._capture()
        route = self.server.routes.get(self.path.split("?")[0])
        if route is None:
            self._reply(404)
            return
        code, payload, headers = route
        self._reply(code, payload, headers)

    def log_message(self, *args):
        pass


def start_wire(routes):
    srv = HTTPServer(("127.0.0.1", 0), WireRecorder)
    srv.requests = []
    srv.routes = routes
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv


