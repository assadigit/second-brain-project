def dec_result(fn):
    try:
        data, truncated = fn()
        return {"data_len": len(data), "truncated": truncated,
                "head": data[:16].decode("utf-8", "replace")}
    except Exception as e:
        # The class name only: it is what the app's own reason line
        # carries ("{encoding} decode failed: {class}"), and the
        # runtime's message text (a Python repr of the bad bytes) is
        # not byte-portable.
        return {"error_class": type(e).__name__}


