def main() -> int:
    out = REPO_ROOT / "internal" / "notereads" / "testdata"
    out.mkdir(parents=True, exist_ok=True)

    app_dir = Path(DEFAULT_APP_DIR).resolve()
    if not (app_dir / "gitcurator" / "core" / "note_reads.py").exists():
        sys.exit(f"[goldens] reference app not found at {app_dir}")
    rev = "unknown"
    try:
        proc = subprocess.run(["git", "-C", str(app_dir.parent), "rev-parse", "HEAD"],
                              capture_output=True, text=True)
        if proc.returncode == 0:
            rev = proc.stdout.strip()
    except OSError:
        pass
    if rev != PINNED_REV:
        print(f"[goldens] WARNING: reference rev {rev} != pinned {PINNED_REV}",
              file=sys.stderr)

    env = dict(os.environ)
    env["GC_APP_DIR"] = str(app_dir)
    env["GOLDEN_OUT_DIR_NOTEREADS"] = str(out)
    env["PYTHONDONTWRITEBYTECODE"] = "1"  # keep the reference repo pristine
    proc = subprocess.run([DEFAULT_PY, "-c", PAYLOAD], env=env,
                          capture_output=True, text=True)
    if proc.returncode != 0:
        sys.exit(f"[goldens] reference run failed:\n{proc.stderr}")
    summary = json.loads(proc.stdout)
    print(f"[goldens] generated internal/notereads testdata "
          f"({len(summary)} stat keys)")
    print(f"[goldens] reference rev: {rev} (pinned: {PINNED_REV})")
    print(f"[goldens] parse cases: {summary['parse_cases']} "
          f"(body tag: {summary['body_tag_cases']}, "
          f"read-bounded: {summary['read_bounded_cases']})")
    print(f"[goldens] fixture sha256: {summary['fixture_sha256']} "
          f"({summary['fixture_rows']} rows, clean close, "
          f"no sidecars: {summary['no_sidecars']})")
    print(f"[goldens] caching pass stats: {summary['pass_stats']}")
    print(f"[goldens] fixture banish marks: {summary['fixture_marks']}")
    print(f"[goldens] pragmas through the reference's own open: "
          f"{summary['pragmas']}")
    print(f"[goldens] behavior probes: {summary['behavior_probes']}")
    return 0


