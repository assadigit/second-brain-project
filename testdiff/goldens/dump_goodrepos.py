def main() -> int:
    if not os.path.isdir(DEFAULT_APP_DIR):
        print(f"reference app dir missing: {DEFAULT_APP_DIR}", file=sys.stderr)
        return 2
    rev = subprocess.run(
        ["git", "-C", os.path.dirname(DEFAULT_APP_DIR), "rev-parse", "HEAD"],
        capture_output=True, text=True,
    ).stdout.strip()
    if rev != PINNED_REV:
        print(f"reference rev {rev} != pinned {PINNED_REV}", file=sys.stderr)
        return 2
    env = dict(os.environ)
    env["GC_APP_DIR"] = DEFAULT_APP_DIR
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run(
        [DEFAULT_PY, "-c", PAYLOAD], capture_output=True, text=True, env=env,
    )
    if proc.returncode != 0:
        print(proc.stderr, file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(proc.stdout, encoding="utf-8")
    print(f"wrote {OUT_FILE} ({len(proc.stdout)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
