def _guard(repo_name='', allow_create=False, responses=None):
    calls = []
    def api(method, path, body=None):
        calls.append([method, path, body])
        table = responses or {}
        key = (method, path)
        if key in table:
            return table[key]
        return (404, {'message': 'Not Found'})
    s = gr.GoodRepos(vault_path='/tmp/guard', token='tok',
                     repo_name=repo_name, auto_push=True,
                     allow_create=allow_create)
    s._api = api
    ok, err = s._ensure_repo()
    return {'ok': ok, 'err': err, 'calls': calls}

