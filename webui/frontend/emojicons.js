// Resolve a glyph name across BOTH packs (the locked reference pack
// first, the extended pack second).
const RESOLVE_CACHE = new Map();
function resolveIcon(name) {
  if (RESOLVE_CACHE.has(name)) return RESOLVE_CACHE.get(name);
  let owner = null;
  try {
    const probe = svgEl(name);
    if (probe.innerHTML && probe.innerHTML.trim() !== '') owner = 'locked';
  } catch (e) { /* unknown in the locked pack */ }
  if (owner === null && EXT_PACK[name] !== undefined) owner = 'ext';
  RESOLVE_CACHE.set(name, owner);
  return owner;
}

// buildGlyph — one inline SVG element for a mapped icon name, riding
// the locked pack's svgEl when the name lives there, the extended
// pack's own builder otherwise (the same wrapper law: 24×24 viewBox,
// 2px round strokes, currentColor).
function buildExtEl(name) {
  const wrap = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  wrap.setAttribute('viewBox', '0 0 24 24');
  wrap.setAttribute('fill', 'none');
  wrap.setAttribute('stroke', 'currentColor');
  wrap.setAttribute('stroke-width', '2');
  wrap.setAttribute('stroke-linecap', 'round');
  wrap.setAttribute('stroke-linejoin', 'round');
  wrap.innerHTML = EXT_PACK[name];
  return wrap;
}
export function glyphFor(name) {
  const owner = resolveIcon(name);
  if (owner === 'locked') return svgEl(name);
  if (owner === 'ext') return buildExtEl(name);
  return null;
}

// The matcher: one alternation over the map's canonical keys, each
// followed by an OPTIONAL U+FE0F variation selector (the engines emit
// both spellings — '⚠' and '⚠️' — and both must match). The emoji set
// is closed — a new engine emoji simply renders as its text self until
// mapped.
const EMOJI_RE = new RegExp(
  '(' + Object.keys(EMOJI_MAP)
    .map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|') + ')(\uFE0F?)', 'g');

// hasEmoji — the cheap test (the flood fast path). lastIndex-safe.
export function hasEmoji(text) {
  return testClean(text);
}
// Reset the regex's lastIndex (EMOJI_RE is global — .test advances it).
function testClean(text) {
  EMOJI_RE.lastIndex = 0;
  const hit = EMOJI_RE.test(text);
  EMOJI_RE.lastIndex = 0;
  return hit;
}

// emojiconEl — the inline glyph wrapper (span.emojicon > svg).
function emojiconEl(name) {
  const span = document.createElement('span');
  span.className = 'emojicon';
  const g = glyphFor(name);
  if (g) span.appendChild(g);
  return span;
}

// stripLeadingEmoji — when a line OPENS with a mapped emoji (the
// engines' house style: "⚡ The one-open law: …"), split it off:
// { emoji, rest } (emoji null when the line opens with plain text).
// The desk renders that leading emoji's glyph in the level-glyph seat
// (level-colored) instead of twice beside the timestamp.
const LEAD_RE = new RegExp('^\\s*(' +
  Object.keys(EMOJI_MAP)
    .map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('|') + ')(\\uFE0F?)\\s*');
export function stripLeadingEmoji(text) {
  if (!text) return { emoji: null, rest: text || '' };
  const m = LEAD_RE.exec(text);
  if (!m) return { emoji: null, rest: text };
  return { emoji: m[1], rest: text.slice(m[0].length) };
}

// iconify — walk the subtree's text nodes; every mapped emoji becomes
// a real glyph. Text nodes only (never re-walks the svgs it made: the
// glyphs contain no text children).
export function iconify(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const pending = [];
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeValue && testClean(n.nodeValue)) pending.push(n);
  }
  for (const node of pending) {
    const text = node.nodeValue;
    EMOJI_RE.lastIndex = 0;
    const frag = document.createDocumentFragment();
    let last = 0;
    let m;
    while ((m = EMOJI_RE.exec(text)) !== null) {
      if (m.index > last) frag.appendChild(document.createTextNode(text.slice(last, m.index)));
      frag.appendChild(emojiconEl(EMOJI_MAP[m[1]]));
      last = m.index + m[0].length;
    }
    if (last < text.length) frag.appendChild(document.createTextNode(text.slice(last)));
    node.parentNode.replaceChild(frag, node);
  }
}

