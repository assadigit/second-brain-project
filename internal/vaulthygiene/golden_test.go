var vhGolden map[string]any

func loadVHGolden(t *testing.T) map[string]any {
	t.Helper()
	if vhGolden != nil {
		return vhGolden
	}
	data, err := os.ReadFile("testdata/vaulthygiene.golden.json")
	if err != nil {
		t.Fatalf("golden file: %v", err)
	}
	var g map[string]any
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatalf("golden json: %v", err)
	}
	vhGolden = g
	return g
}

func vhSection(t *testing.T, name string) map[string]any {
	t.Helper()
	v, ok := loadVHGolden(t)[name].(map[string]any)
	if !ok {
		t.Fatalf("golden section %q missing or not an object", name)
	}
	return v
}

// cmpVHGolden compares through the canonical Python dumps (maps sort
// keys; slices keep order) so the comparison is byte-honest (the
// chrometabs/vaultscan pattern).
func cmpVHGolden(t *testing.T, what string, got, want any) {
	t.Helper()
	g := storage.PyDumps(normVH(got))
	w := storage.PyDumps(normVH(want))
	if g != w {
		t.Errorf("%s diverges from the reference golden:\n got: %s\nwant: %s",
			what, g, w)
	}
}

func normVH(v any) any {
	switch t := v.(type) {
	case string:
		return t
	case int:
		return float64(t)
	case int64:
		return float64(t)
	case bool, float64, nil:
		return t
	case json.Number:
		f, _ := t.Float64()
		return f
	case map[string]any:
		out := map[string]any{}
		for k, val := range t {
			out[k] = normVH(val)
		}
		return out
	case map[string]bool:
		out := map[string]any{}
		for k, val := range t {
			out[k] = val
		}
		return out
	case map[string]int:
		out := map[string]any{}
		for k, val := range t {
			out[k] = float64(val)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = normVH(val)
		}
		return out
	case []string:
		out := make([]any, len(t))
		for i, s := range t {
			out[i] = s
		}
		return out
	case []bool:
		out := make([]any, len(t))
		for i, b := range t {
			out[i] = b
		}
		return out
	default:
		return t
	}
}

// sortedKeysOf renders a Go set as the golden's sorted list (the
// reference's Python sets dump sorted by the generator).
func sortedKeysOf(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

