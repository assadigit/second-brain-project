// cmpDSGolden compares through the canonical Python dumps (maps sort
// keys; slices keep order) so the comparison is byte-honest.
func cmpDSGolden(t *testing.T, what string, got, want any) {
	t.Helper()
	g := storage.PyDumps(normDS(got))
	w := storage.PyDumps(normDS(want))
	if g != w {
		t.Errorf("%s diverges from the reference golden:\n got: %s\nwant: %s",
			what, g, w)
	}
}

// normDS normalizes Go values and JSON-decoded golden values onto the
// same comparable shape (the goodrepos normGR twin).
func normDS(v any) any {
	switch t := v.(type) {
	case string:
		return t
	case int:
		return float64(t)
	case int64:
		return float64(t)
	case bool, float64, nil:
		return t
	case json.Number:
		f, _ := t.Float64()
		return f
	case *storage.OrderedMap:
		if t == nil {
			return nil
		}
		out := map[string]any{}
		for _, k := range t.Keys() {
			val, _ := t.Get(k)
			out[k] = normDS(val)
		}
		return out
	case map[string]any:
		if t == nil {
			return nil
		}
		out := map[string]any{}
		for k, val := range t {
			out[k] = normDS(val)
		}
		return out
	case map[string]string:
		out := map[string]any{}
		for k, val := range t {
			out[k] = val
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = normDS(val)
		}
		return out
	case []string:
		out := make([]any, len(t))
		for i, s := range t {
			out[i] = s
		}
		return out
	case CommandResult:
		return normDS(commandResultMap(&t))
	default:
		return fmt.Sprintf("%v", v)
	}
}

func commandResultMap(r *CommandResult) *storage.OrderedMap {
	m := storage.NewOrderedMap()
	m.Set("command_id", r.ID)
	m.Set("status", r.Status)
	m.Set("error", r.Error)
	return m
}

// freezeClock mirrors the generator's _FrozenDatetime (2026-01-01
// 12:34:00) and restores the real clock afterwards.
func freezeClock(t *testing.T) {
	t.Helper()
	old := clockNow
	clockNow = func() time.Time {
		return time.Date(2026, 1, 1, 12, 34, 0, 0, time.UTC)
	}
	t.Cleanup(func() { clockNow = old })
}

// freezeGitDates mirrors the generator's GIT_AUTHOR_DATE /
// GIT_COMMITTER_DATE (the deterministic mirror commit sha).
func freezeGitDates(t *testing.T) {
	t.Helper()
	t.Setenv("GIT_AUTHOR_DATE", "2026-01-01T12:34:56+00:00")
	t.Setenv("GIT_COMMITTER_DATE", "2026-01-01T12:34:56+00:00")
}

// foldDS folds the Go run's per-run paths away (the generator's fold
// twin): vault → '<vault>'.
func foldDS(obj any, vault string) any {
	switch t := obj.(type) {
	case string:
		if vault != "" && strings.HasPrefix(t, vault) {
			return "<vault>" + t[len(vault):]
		}
		return t
	case *storage.OrderedMap:
		out := storage.NewOrderedMap()
		for _, k := range t.Keys() {
			v, _ := t.Get(k)
			out.Set(k, foldDS(v, vault))
		}
		return out
	case map[string]any:
		out := map[string]any{}
		for k, v := range t {
			out[k] = foldDS(v, vault)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, v := range t {
			out[i] = foldDS(v, vault)
		}
		return out
	case []string:
		out := make([]any, len(t))
		for i, v := range t {
			out[i] = foldDS(v, vault)
		}
		return out
	case CommandResult:
		return foldDS(commandResultMap(&t), vault)
	default:
		return obj
	}
}

