var mirrorGolden map[string]any

func loadMGolden(t *testing.T) map[string]any {
	t.Helper()
	if mirrorGolden != nil {
		return mirrorGolden
	}
	data, err := os.ReadFile("testdata/mirror.golden.json")
	if err != nil {
		t.Fatalf("golden file: %v", err)
	}
	var g map[string]any
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatalf("golden json: %v", err)
	}
	mirrorGolden = g
	return g
}

func mSection(t *testing.T, name string) map[string]any {
	t.Helper()
	v, ok := loadMGolden(t)[name].(map[string]any)
	if !ok {
		t.Fatalf("golden section %q missing or not an object", name)
	}
	return v
}

func mValue(t *testing.T, name string) any {
	t.Helper()
	v, ok := loadMGolden(t)[name]
	if !ok {
		t.Fatalf("golden value %q missing", name)
	}
	return v
}

// foldM folds the Go temp root away exactly like the generator's fold.
func foldM(v any, root string) any {
	switch x := v.(type) {
	case string:
		return strings.ReplaceAll(x, root, "<tmp>")
	case []any:
		out := make([]any, len(x))
		for i, e := range x {
			out[i] = foldM(e, root)
		}
		return out
	case map[string]any:
		out := map[string]any{}
		for k, e := range x {
			out[k] = foldM(e, root)
		}
		return out
	}
	return v
}

// normM normalizes Go values and JSON-decoded golden values onto the
// same comparable shape (the T-49 normDS twin: ints ride float64,
// OrderedMap flattens).
func normM(v any) any {
	switch t := v.(type) {
	case string:
		return t
	case int:
		return float64(t)
	case int64:
		return float64(t)
	case bool, float64, nil:
		return t
	case json.Number:
		f, _ := t.Float64()
		return f
	case *storage.OrderedMap:
		out := map[string]any{}
		for _, k := range t.Keys() {
			val, _ := t.Get(k)
			out[k] = normM(val)
		}
		return out
	case map[string]any:
		out := map[string]any{}
		for k, val := range t {
			out[k] = normM(val)
		}
		return out
	case map[string]string:
		out := map[string]any{}
		for k, val := range t {
			out[k] = val
		}
		return out
	case map[string]bool:
		out := map[string]any{}
		for k, val := range t {
			out[k] = val
		}
		return out
	case map[string]int:
		out := map[string]any{}
		for k, val := range t {
			out[k] = float64(val)
		}
		return out
	case []any:
		out := make([]any, len(t))
		for i, val := range t {
			out[i] = normM(val)
		}
		return out
	case []string:
		out := make([]any, len(t))
		for i, s := range t {
			out[i] = s
		}
		return out
	case []bool:
		out := make([]any, len(t))
		for i, b := range t {
			out[i] = b
		}
		return out
	default:
		return t
	}
}

// cmpM compares through the canonical Python dumps (maps sort keys;
// slices keep order) so the comparison is byte-honest.
func cmpM(t *testing.T, what string, got, want any) {
	t.Helper()
	g := storage.PyDumps(normM(got))
	w := storage.PyDumps(normM(want))
	if g != w {
		t.Errorf("%s diverges from the reference golden:\n got: %s\nwant: %s",
			what, g, w)
	}
}

// pyList builds []any from any slice of maps (never nil — the
// []-vs-null byte law).
func pyList(items ...any) []any {
	out := []any{}
	return append(out, items...)
}

