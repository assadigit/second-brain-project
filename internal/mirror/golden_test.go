// sortedAny sorts a string slice into []any.
func sortedAny(items []string) []any {
	s := append([]string{}, items...)
	sortStrings(s)
	out := []any{}
	for _, x := range s {
		out = append(out, x)
	}
	return out
}

// sortByKey sorts items by a string key (stable).
func sortByKey[T any](items []T, key func(T) string) {
	sort.SliceStable(items, func(i, j int) bool { return key(items[i]) < key(items[j]) })
}

