// Package webfetch ports core/web_fetch.py — the polite fetcher and
// the machine half of the five-door ladder (T-31, Phase 3): the
// proxy/direct/loopback routes, the redirect ladder with cookies, the
// Chrome-131 header set, the rate limiter with penalties, the size and
// time caps, the capped decompression, the failure-category taxonomy,
// the DoH verdicts, the Wayback rescue, and the impersonation door.
//
// Spec: docs/port-blueprint/module-specs/spec-core-web-fetch.md;
// ADR-0006 (network stack; tls-client pinned at v1.16.0 by Am.1+2).
//
// THE PACKAGE LAWS:
//   - A fetch that cannot complete is DATA (status "failed"), never a
//     panic — one failing link never stops the batch.
//   - The WIRE is the contract: the payload golden
//     (testdata/webfetch_payloads.golden.json, generated by
//     testdiff/goldens/dump_webfetch.py from the unmodified reference)
//     pins the requests (method, path, header set); the pure golden
//     pins the Chrome-131 header ORDER (the app's construction order).
//   - Loopback never rides a proxy (the v0.15.1 law) — enforced ahead
//     of the route builder, never escaped by any door.
//   - SOCKS5 dials with the hostname UNRESOLVED (rdns=True — DNS at
//     the proxy exit); the http-type proxy rides the absolute-URI
//     ProxyURL (proxy-side DNS, the same protection).
//   - The redirect ladder is OUR loop (CheckRedirect ErrUseLastResponse
//   - manual hops): hop cookies ride along, 308 is followed, loops
//     are named, a redirect with no Location is an honest
//     redirect_broken failure.
//   - The rate-limit penalty law: a 429/503 leg pays the site's
//     Retry-After (or the 60 s default, capped at 300 s) into the
//     domain limiter.
//
// DOCUMENTED DIVERGENCES (each recorded per the port law):
//   - Go's net/http writes outgoing header NAMES in sorted order; the
//     Chrome-131 navigation ORDER is golden-pinned as data (the
//     RequestHeaders construction order) but the stdlib door cannot
//     reproduce it on the wire. The fingerprint-order walls are the
//     third door's jurisdiction (tls-client/fhttp preserves Chrome's
//     order) — the reason the third door exists.
//   - Direct routes set Transport.Proxy = nil — no environment-proxy
//     honor (ADR-0006 §1's explicit decision; Python's default opener
//     would read env proxies, a corner no test pins and the app's own
//     proxy config supersedes).
//   - The door ships armed: tls-client is compiled in, so
//     impersonatorAvailable defaults TRUE — the "pip install curl_cffi"
//     hint never appears in production (ADR-0006 §4 dropped the
//     self-install; the seam keeps the logic testable and the
//     autopip option is read and honored through it as a no-op
//     default). The fake-session and availability seams preserve the
//     reference's decision structure byte-for-byte.
//   - One cached impersonation session (the cookie-persistence law):
//     tls-client takes its proxy per-CLIENT, so the single session
//     internally holds one client per route sharing one cookie jar —
//     observably the same as curl_cffi's per-request proxies.
//   - Python's per-read socket timeout and its send-phase/receive-phase
//     split collapse into http.Client.Timeout; every timeout-class
//     failure reports reason "timeout" (the /slow pin). The
//     connect-phase "connection: timed out" nuance is not reachable in
//     Go's client model and is unpinned.
//   - The runtime's dial/TLS error TEXT differs by runtime (Go's
//     url.Error vs Python's URLError errno); the pinned contract is the
//     reason SHAPE ("connection: …", category, the host:port in the
//     SOCKS WebProxyError line) — the same class of runtime-shaped,
//     unpinned divergence the llmclient port recorded.
//   - The Python marker lists (TLS handshake, DNS) are byte-exact; the
//     Go runtime speaks its own dialects, so the checks ALSO recognize
//     the Go shapes ("tls: handshake failure", "TLS handshake timeout",
//     "no such host" rides the shared marker) — the marker law's intent
//     (recognize the same real-world walls) transfers.
//   - Python exception-class prefixes in user-visible reasons (the
//     decode-failure "{encoding} decode failed: ValueError /
//     BadGzipFile" line) are kept — the house precedent from the
//     llmclient port (detect_ollama's failure details).
